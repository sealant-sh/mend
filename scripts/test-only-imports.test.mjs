// scripts/ci-scope.mjs skips the mobile and packaging lanes for a change confined to a package's
// test/ directory or its *.test.* / *.spec.* files. That holds only while nothing those lanes build
// or run names those files. This guard does not trust import syntax: it reads the text of every
// file the lanes may reach and fails on any path into a package's tests, written whole, relative
// to the file, as adjacent literal pieces, or as an `@mend/<pkg>` specifier whose export lands
// there. A mention in a comment counts too; a harmless one goes in `allowed` with its reason.
//
// Limit: a path assembled from variables (`join(dir, name, "test")`) is invisible to a text scan.

const root = fileURLToPath(new URL("../", import.meta.url));

/** The files the skip treats as test-only, the same set as `testOnly` in scripts/ci-scope.mjs. */
const packageTest = (path) =>
  /^packages\/[^/]+\/(test(\/|$)|(.+\/)?[^/]+\.(test|spec)(\.[^/]*)?$)/.test(path);

const testNamed = (path) => /(^|\/)test\//.test(path) || /\.(test|spec)\.[^/]+$/.test(path);

/**
 * Files outside the scan, by reason. Everything else that is text is scanned: production sources,
 * build and packaging scripts, test fixtures under test-fixtures/ (packaging reads
 * apps/cli/test-fixtures), configs, Dockerfiles, deploy files and package manifests.
 */
const outOfScope = [
  // Tests and their own helpers run in the Turbo test lanes, which a test-only change still runs.
  // The packaging lane's own test files are added back from the CI job that names them.
  [testNamed, "a test"],
  [(path) => /(^|\/)vitest(\.[^/]+)?\.config\.[cm]?[jt]s$/.test(path), "a Vitest config"],
  // Turbo task inputs: read only by Turbo, whose lanes always run.
  [(path) => /(^|\/)turbo\.json$/.test(path), "a Turbo task definition"],
  // Prose. The docs site renders apps/docs content; it never reads the files a page names.
  [(path) => /\.mdx?$/.test(path), "prose"],
  // ci.yml is scanned job by job below; ci-measure.yml is generated from it.
  [(path) => /^\.github\/workflows\/ci(-measure)?\.yml$/.test(path), "scanned per job"],
  [(path) => path === "pnpm-lock.yaml", "generated by pnpm"],
];

/**
 * Harmless mentions, each with its reason: `file` names a package test path in a way neither lane
 * acts on. Keep this short; a new entry needs a reason a reviewer can check.
 */
const allowed = [];

// An export's target paths, through any nesting of conditions and arrays.
const targets = (value) =>
  typeof value === "string"
    ? [value]
    : value && typeof value === "object"
      ? Object.values(value).flatMap(targets)
      : [];

const testTarget = (target) =>
  /^\.\/test(\/|$)/.test(target) || /(^|\/)[^/]*\.(test|spec)(\.[^/]*)?$/.test(target);

/**
 * Per package name: its directory, and the subpath patterns of every export that is test-only (a
 * `./testing` key, or a target at any nesting under ./test/ or naming a test or spec file). A
 * string or conditions-only `exports` is the root export ".".
 */
const packageIndex = (manifests) =>
  new Map(
    manifests.map(({ dir, manifest }) => {
      const { exports } = manifest;
      const map =
        typeof exports === "string" ||
        Array.isArray(exports) ||
        (exports && !Object.keys(exports).some((key) => key.startsWith(".")))
          ? { ".": exports }
          : (exports ?? {});
      const patterns = Object.entries(map)
        .filter(([key, value]) => /^\.\/testing(\/|$)/.test(key) || targets(value).some(testTarget))
        .map(([key]) => {
          const subpath = key === "." ? "" : key.slice(2);
          const escaped = subpath.replace(/[.+?^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".+");
          return new RegExp(subpath === "" ? "^$" : `^${escaped}(/.*)?$`);
        });
      return [manifest.name, { dir, patterns }];
    }),
  );

// A string literal: double- or single-quoted on one line, or a template.
const literal = /"((?:[^"\\\n]|\\.)*)"|'((?:[^'\\\n]|\\.)*)'|`((?:[^`\\]|\\.)*)`/g;

/**
 * Every run of adjacent string literals in `text`, joined as a path: `"a", "b"` (path pieces)
 * joins with a slash and `"a" + "b"` with nothing. A run ends at anything else, so a variable
 * between pieces ends it.
 */
const literalRuns = (text) => {
  const runs = [];
  let current;
  let end = -1;
  for (const match of text.matchAll(literal)) {
    const value = match[1] ?? match[2] ?? match[3];
    const gap = current === undefined ? "" : text.slice(end, match.index);
    if (current !== undefined && /^\s*,\s*$/.test(gap)) current += `/${value}`;
    else if (current !== undefined && /^\s*\+\s*$/.test(gap)) current += value;
    else {
      if (current !== undefined) runs.push(current);
      current = value;
    }
    end = match.index + match[0].length;
  }
  if (current !== undefined) runs.push(current);
  return runs;
};

/**
 * Every package test path that `text` names, relative paths resolved against `base`. Every
 * candidate is normalised first, so `packages/x/src/../test/a` is `packages/x/test/a`. Only this
 * repository's packages count (a pin file may name another repository's `packages/…`), and so
 * does a templated package name, as in `packages/${name}/test`.
 */
const mentions = (text, packages, base) => {
  const dirs = new Set([...packages.values()].map(({ dir }) => dir));
  const found = new Set();
  const check = (candidate) => {
    const normal = posix.normalize(candidate);
    for (const match of normal.matchAll(/(?:^|\/)(packages\/[^/]+(?:\/.*)?)/g)) {
      const path = match[1].replace(/[/*.:]+$/, "");
      const dir = /^packages\/[^/]+/.exec(path)?.[0];
      if (dir && (dirs.has(dir) || dir.includes("$")) && packageTest(path)) found.add(path);
    }
  };
  // Relative paths and literal runs resolve against the file; anything else stands as written.
  const place = (path) =>
    path.startsWith("./") || path.startsWith("../") || path === ".."
      ? posix.join(base, path)
      : path;
  // A path written whole, absolute or embedded anywhere: in a string, a template, a comment.
  // The path reaches back to its token's start, so `/repo/packages/x/src/../test` normalises.
  const boundary = /[\s"'`(),;[\]{}<>|&=\\]/;
  for (const match of text.matchAll(/packages\/[\w.${}-]+\/[^\s"'`),;\]}<>|&\\]*/g)) {
    let start = match.index;
    while (start > 0 && !boundary.test(text[start - 1])) start -= 1;
    check(text.slice(start, match.index) + match[0]);
  }
  // A relative path outside any literal, as a Dockerfile or a shell command writes one.
  for (const token of text.split(/[\s"'`,()[\]{}=;<>|&]+/)) {
    if (token.startsWith("./") || token.startsWith("../")) check(place(token));
  }
  // Adjacent literal pieces of any length: join(root, "packages", "db", "src", "a.test.ts"),
  // join(import.meta.dirname, "..", "test") or "packages/" + "db/test".
  for (const run of literalRuns(text)) check(place(run));
  // A package specifier, whatever syntax or comment surrounds it.
  for (const match of text.matchAll(/@mend\/([\w.-]+)((?:\/[\w.*-]+)*)/g)) {
    const known = packages.get(`@mend/${match[1]}`);
    const subpath = match[2].slice(1);
    if (
      /^test(ing)?(\/|$)/.test(subpath) ||
      known?.patterns.some((pattern) => pattern.test(subpath)) ||
      (known && subpath && packageTest(`${known.dir}/${subpath}`))
    ) {
      found.add(match[0]);
    }
  }
  return [...found];
};

const pathFields = [
  "main",
  "module",
  "types",
  "typings",
  "browser",
  "bin",
  "files",
  "react-native",
];

/**
 * A manifest's scanned text: every field but its name, dependency maps and its own exports (an
 * export into test/ is what makes a specifier test-only above), and every test script. Path
 * fields also resolve bare relative entries, as `files: ["test"]` or `main: "test/index.js"`.
 */
const manifestText = (manifest) => {
  const {
    name: _name,
    exports: _exports,
    dependencies: _dependencies,
    devDependencies: _devDependencies,
    peerDependencies: _peerDependencies,
    optionalDependencies: _optionalDependencies,
    scripts = {},
    ...rest
  } = manifest;
  const kept = Object.fromEntries(
    Object.entries(scripts).filter(([key]) => !/^test(:|$)/.test(key)),
  );
  const bare = pathFields
    .flatMap((field) => targets(manifest[field]))
    .map((path) => (path.startsWith(".") || path.startsWith("/") ? path : `./${path}`));
  return [...targets(kept), ...targets(rest), ...bare].join("\n");
};

/**
 * The jobs gated on the mobile or packaging scope, by name, with every string in the job at any
 * depth (env, with, container, services, defaults, strategy.matrix, steps) and in the
 * workflow-level env and defaults the job inherits.
 */
const gatedJobs = (workflow) =>
  Object.entries(workflow?.jobs ?? {})
    .filter(([, job]) => /needs\.changes\.outputs\.(mobile|packaging)\b/.test(String(job.if ?? "")))
    .map(([name, job]) => [
      name,
      targets([job, workflow.env ?? {}, workflow.defaults ?? {}]).join("\n"),
    ]);

/**
 * Every place a file the mobile or packaging lane may reach names a package's tests. `files`
 * maps repository paths to contents; `manifests` lists each package's directory and manifest;
 * `workflow` is the parsed ci.yml.
 */
const findTestReaches = ({ files, manifests, workflow }) => {
  const packages = packageIndex(manifests.filter(({ dir }) => dir.startsWith("packages/")));
  const found = [];
  const report = (file, text, base) => {
    for (const mention of mentions(text, packages, base)) {
      const permitted = allowed.some((entry) => entry.file === file && entry.mention === mention);
      if (!permitted) found.push(`${file}: names ${mention}`);
    }
  };
  for (const [file, text] of files) {
    if (/(^|\/)package\.json$/.test(file)) {
      report(file, manifestText(JSON.parse(text)), dirname(file));
    } else {
      // A Dockerfile's sources are relative to its build context, the repository root.
      report(file, text, /(^|\/)([^/]+\.)?Dockerfile$/.test(file) ? "." : dirname(file));
    }
  }
  for (const [name, text] of gatedJobs(workflow)) {
    report(`.github/workflows/ci.yml job ${name}`, text, ".");
  }
  return found;
};

const git = (...args) =>
  execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 1 << 26 })
    .split("\0")
    .filter(Boolean);

const repository = () => {
  const workflow = parse(readFileSync(resolve(root, ".github/workflows/ci.yml"), "utf8"));
  // The packaging lane's own tests: every file or glob its gated jobs name.
  const laneFiles = new Set(
    gatedJobs(workflow).flatMap(([, text]) =>
      text
        .split(/\s+/)
        .filter((token) => /^[\w.][\w./*-]*\.[cm]?[jt]s$/.test(token))
        .flatMap((token) => globSync(token, { cwd: root })),
    ),
  );
  const listed = git("ls-files", "-z", "--cached", "--others", "--exclude-standard").filter(
    (path) => existsSync(resolve(root, path)),
  );
  const files = new Map();
  for (const path of listed) {
    if (!laneFiles.has(path) && outOfScope.some(([skip]) => skip(path))) continue;
    const text = readFileSync(resolve(root, path));
    if (text.length > 4 << 20 || text.includes(0)) continue;
    files.set(path, text.toString("utf8"));
  }
  const manifests = listed
    .filter((path) => /^(packages|apps|tooling)\/[^/]+\/package\.json$/.test(path))
    .map((path) => ({
      dir: dirname(path),
      manifest: JSON.parse(readFileSync(resolve(root, path), "utf8")),
    }));
  return { files, manifests, workflow, laneFiles };
};

test("nothing the mobile or packaging lane builds, reads or runs names a package's tests", () => {
  const tree = repository();
  // The guard must see the ./testing exports it exists for, read from the manifests.
  const packages = packageIndex(tree.manifests.filter(({ dir }) => dir.startsWith("packages/")));
  for (const name of ["@mend/db", "@mend/sessions", "@mend/store"]) {
    assert.equal(packages.get(name)?.patterns.length, 1, name);
    assert.ok(packages.get(name).patterns[0].test("testing"), name);
  }
  for (const path of [
    "apps/api/src/access.ts",
    "scripts/bundle-health.mjs",
    "scripts/bundle-packaging.test.mjs",
    ".claude/skills/verify/scripts/leaks.test.mjs",
    "apps/mobile/package.json",
    "package.json",
    "Dockerfile",
    "deploy/helm/mend/values.yaml",
  ]) {
    assert.ok(tree.files.has(path), `the scan must include ${path}`);
  }
  assert.ok(
    !tree.files.has("scripts/ci-scope.test.mjs"),
    "tests outside the lanes are not scanned",
  );
  assert.deepEqual(findTestReaches(tree), []);
  for (const entry of allowed) {
    assert.ok(tree.files.get(entry.file)?.includes(entry.mention), `stale allowance ${entry.file}`);
  }
});

