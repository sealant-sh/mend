import { parse } from "yaml";

// An early warning, not the enforcement. scripts/ci-scope.mjs skips the mobile-web and packaging
// lanes for a change confined to package tests; what enforces that those lanes never need them is
// the first lane step, scripts/remove-package-tests.mjs, which deletes them so a lane that reads
// one fails. This guard only spots the plain cases sooner, in the static job: an import of a
// test-only package export, or a literal `packages/<pkg>/test/…` or `*.test.*` / `*.spec.*` path in
// non-test code, the lanes' own test files, package manifests or the lane jobs.
//
// Its gaps are not blockers; the deletion step covers them. It misses a path assembled from
// variables or from separate literals (`join(root, "packages", name, "test")`), a path relative to
// some other directory (a package script's `cat test/x`, a step's `working-directory`), and a file
// a lane reaches indirectly (a package script, or a script that calls another).

const root = fileURLToPath(new URL("../", import.meta.url));

/** A package's tests: its test/ directory, or a test or spec file anywhere in it. */
const packageTest = (path) =>
  /^packages\/[^/]+\/(test(\/|$)|(.+\/)?[^/]+\.(test|spec)(\.[^/]*)?$)/.test(path);

const testNamed = (path) => /(^|\/)test\//.test(path) || /\.(test|spec)\.[^/]+$/.test(path);

/** Files the warning does not read, each with its reason. Everything else that is text is read. */
const outOfScope = [
  // Tests run in the Turbo test lanes, which a test-only change still runs. The lanes' own test
  // files are added back from the jobs that name them.
  [testNamed, "a test"],
  [(path) => /(^|\/)vitest(\.[^/]+)?\.config\.[cm]?[jt]s$/.test(path), "a Vitest config"],
  [(path) => /(^|\/)turbo\.json$/.test(path), "a Turbo task definition, read only by Turbo"],
  [(path) => /\.mdx?$/.test(path), "prose"],
  [(path) => /^\.github\/workflows\/ci(-measure)?\.yml$/.test(path), "read per lane job below"],
  [(path) => path === "pnpm-lock.yaml", "generated by pnpm"],
];

/** Harmless mentions, `{ file, mention, reason }`. Keep this short. */
const allowed = [];

// An export's target paths, through any nesting of conditions and arrays.
const targets = (value) =>
  typeof value === "string"
    ? [value]
    : value && typeof value === "object"
      ? Object.values(value).flatMap(targets)
      : [];

/**
 * Per package name: its directory, and the subpath patterns of every test-only export (a
 * `./testing` key, or a target at any nesting under ./test/ or naming a test or spec file). A
 * string or conditions-only `exports` is the root export ".", and `*` matches as a wildcard.
 */
const packageIndex = (manifests) =>
  new Map(
    manifests.map(({ dir, manifest }) => {
      const { exports } = manifest;
      const map =
        typeof exports === "string" ||
        Array.isArray(exports) ||
        (exports && !Object.keys(exports).some((key) => key.startsWith(".")))
          ? { ".": exports }
          : (exports ?? {});
      const patterns = Object.entries(map)
        .filter(
          ([key, value]) =>
            /^\.\/testing(\/|$)/.test(key) ||
            targets(value).some(
              (target) => /^\.\/test(\/|$)/.test(target) || /\.(test|spec)(\.[^/]*)?$/.test(target),
            ),
        )
        .map(([key]) => {
          const subpath = key === "." ? "" : key.slice(2);
          const escaped = subpath.replace(/[.+?^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".+");
          return new RegExp(subpath === "" ? "^$" : `^${escaped}(/.*)?$`);
        });
      return [manifest.name, { dir, patterns }];
    }),
  );

/**
 * The package test paths and test-only specifiers `text` names. Paths are normalised, and
 * `./`/`../` ones resolve against `base`. Only this repository's packages count: a pin file may
 * name another repository's `packages/…`.
 */
const mentions = (text, packages, base) => {
  const dirs = new Set([...packages.values()].map(({ dir }) => dir));
  const found = new Set();
  const check = (candidate) => {
    for (const match of posix.normalize(candidate).matchAll(/(?:^|\/)(packages\/[^/]+.*)/g)) {
      const path = match[1].replace(/[/*.:]+$/, "");
      const dir = /^packages\/[^/]+/.exec(path)?.[0];
      if (dir && (dirs.has(dir) || dir.includes("$")) && packageTest(path)) found.add(path);
    }
  };
  // A literal path, from the start of its word, so `/repo/packages/x/src/../test` normalises.
  const boundary = /[\s"'`(),;[\]{}<>|&=\\]/;
  for (const match of text.matchAll(/packages\/[\w.${}-]+\/[^\s"'`),;\]}<>|&\\]*/g)) {
    let start = match.index;
    while (start > 0 && !boundary.test(text[start - 1])) start -= 1;
    check(text.slice(start, match.index) + match[0]);
  }
  for (const word of text.split(/[\s"'`,()[\]{}=;<>|&]+/)) {
    if (word.startsWith("./") || word.startsWith("../")) check(posix.join(base, word));
  }
  // A specifier of a test-only export, or of a test file inside a package.
  for (const match of text.matchAll(/@mend\/([\w.-]+)((?:\/[\w.*-]+)*)/g)) {
    const known = packages.get(`@mend/${match[1]}`);
    const subpath = match[2].slice(1);
    if (
      /^test(ing)?(\/|$)/.test(subpath) ||
      known?.patterns.some((pattern) => pattern.test(subpath)) ||
      (known && subpath && packageTest(`${known.dir}/${subpath}`))
    ) {
      found.add(match[0]);
    }
  }
  return [...found].filter(
    (path) => ![...found].some((other) => other !== path && path.startsWith(`${other}/`)),
  );
};

/** A manifest's text without its name, its dependency maps, its own exports or its test scripts. */
const manifestText = (manifest) => {
  const {
    name: _name,
    exports: _exports,
    dependencies: _dependencies,
    devDependencies: _devDependencies,
    peerDependencies: _peerDependencies,
    optionalDependencies: _optionalDependencies,
    scripts = {},
    ...rest
  } = manifest;
  const kept = Object.entries(scripts).filter(([key]) => !/^test(:|$)/.test(key));
  return [...targets(Object.fromEntries(kept)), ...targets(rest)].join("\n");
};

/** The jobs gated on the mobile or packaging scope, with their strings and the workflow env. */
const laneJobs = (workflow) =>
  Object.entries(workflow?.jobs ?? {})
    .filter(([, job]) => /needs\.changes\.outputs\.(mobile|packaging)\b/.test(String(job.if ?? "")))
    .map(([name, job]) => [name, targets([job, workflow.env ?? {}]).join("\n")]);

/** The files the lane jobs name, quoted or not, `--flag=value` included, globs expanded. */
const laneFilesOf = (workflow, glob) =>
  new Set(
    laneJobs(workflow).flatMap(([, text]) =>
      text
        .split(/[\s"'=]+/)
        .filter((word) => /^[\w.][\w./*-]*$/.test(word) && word.includes("."))
        .flatMap(glob),
    ),
  );

const findTestReaches = ({ files, manifests, workflow }) => {
  const packages = packageIndex(manifests.filter(({ dir }) => dir.startsWith("packages/")));
  const found = [];
  const report = (file, text, base) => {
    for (const mention of mentions(text, packages, base)) {
      if (!allowed.some((entry) => entry.file === file && entry.mention === mention)) {
        found.push(`${file}: names ${mention}`);
      }
    }
  };
  for (const [file, text] of files) {
    if (/(^|\/)package\.json$/.test(file))
      report(file, manifestText(JSON.parse(text)), dirname(file));
    // A Dockerfile's sources are relative to its build context, the repository root.
    else report(file, text, /(^|\/)([^/]+\.)?Dockerfile$/.test(file) ? "." : dirname(file));
  }
  for (const [name, text] of laneJobs(workflow)) {
    report(`.github/workflows/ci.yml job ${name}`, text, ".");
  }
  return found;
};

const repository = () => {
  const workflow = parse(readFileSync(resolve(root, ".github/workflows/ci.yml"), "utf8"));
  const listed = execFileSync(
    "git",
    ["ls-files", "-z", "--cached", "--others", "--exclude-standard"],
    { cwd: root, encoding: "utf8", maxBuffer: 1 << 26 },
  )
    .split("\0")
    .filter((path) => path && existsSync(resolve(root, path)));
  const tracked = new Set(listed);
  const laneFiles = laneFilesOf(workflow, (word) =>
    globSync(word, { cwd: root }).filter((path) => tracked.has(path)),
  );
  const files = new Map();
  for (const path of listed) {
    if (!laneFiles.has(path) && outOfScope.some(([skip]) => skip(path))) continue;
    const text = readFileSync(resolve(root, path));
    if (text.length > 4 << 20 || text.includes(0)) continue;
    files.set(path, text.toString("utf8"));
  }
  const manifests = listed
    .filter((path) => /^(packages|apps|tooling)\/[^/]+\/package\.json$/.test(path))
    .map((path) => ({
      dir: dirname(path),
      manifest: JSON.parse(readFileSync(resolve(root, path), "utf8")),
    }));
  return { files, manifests, workflow, laneFiles };
};

test("nothing outside the tests names a package's tests (early warning)", () => {
  const tree = repository();
  const packages = packageIndex(tree.manifests.filter(({ dir }) => dir.startsWith("packages/")));
  for (const name of ["@mend/db", "@mend/sessions", "@mend/store"]) {
    assert.equal(packages.get(name)?.patterns.length, 1, name);
    assert.ok(packages.get(name).patterns[0].test("testing"), name);
  }
  for (const path of [
    "apps/api/src/access.ts",
    "scripts/bundle-health.mjs",
    "scripts/bundle-packaging.test.mjs",
    ".claude/skills/verify/scripts/leaks.test.mjs",
    "apps/mobile/package.json",
    "Dockerfile",
  ]) {
    assert.ok(tree.files.has(path), `the warning must read ${path}`);
  }
  assert.ok(!tree.files.has("scripts/ci-scope.test.mjs"), "tests outside the lanes are not read");
  assert.deepEqual(findTestReaches(tree), []);
});

test("test-only exports are found from every export-map shape", () => {
  const index = packageIndex([
    { dir: "packages/a", manifest: { name: "@mend/a", exports: { "./testing": "./src/x.ts" } } },
    {
      dir: "packages/b",
      manifest: { name: "@mend/b", exports: { "./f": { import: "./test/f.ts" } } },
    },
    {
      dir: "packages/c",
      manifest: { name: "@mend/c", exports: { ".": "./src/i.ts", "./f/*": "./test/*.ts" } },
    },
    { dir: "packages/d", manifest: { name: "@mend/d", exports: "./test/index.ts" } },
    { dir: "packages/e", manifest: { name: "@mend/e", exports: { import: "./test/i.ts" } } },
    { dir: "packages/f", manifest: { name: "@mend/f", exports: { "./h": "./src/h.spec.ts" } } },
    {
      dir: "packages/g",
      manifest: { name: "@mend/g", exports: { ".": "./src/i.ts", "./*": "./src/*" } },
    },
  ]);
  const testOnly = (name, subpath) =>
    index.get(name).patterns.some((pattern) => pattern.test(subpath));
  assert.ok(testOnly("@mend/a", "testing") && testOnly("@mend/a", "testing/deep"));
  assert.ok(testOnly("@mend/b", "f"));
  assert.ok(testOnly("@mend/c", "f/postgres") && !testOnly("@mend/c", ""));
  assert.ok(testOnly("@mend/d", "") && testOnly("@mend/e", ""));
  assert.ok(testOnly("@mend/f", "h"));
  assert.ok(!testOnly("@mend/g", "") && !testOnly("@mend/g", "ids"));
});

test("the warning catches plain imports and literal paths, and exempts tests", () => {
  const manifests = [
    {
      dir: "packages/sessions",
      manifest: { name: "@mend/sessions", exports: { "./testing": "./test/testing.ts" } },
    },
    {
      dir: "packages/wild",
      manifest: { name: "@mend/wild", exports: { "./fixtures/*": "./test/*.ts" } },
    },
    {
      dir: "packages/domain",
      manifest: { name: "@mend/domain", exports: { ".": "./src/index.ts" } },
    },
    { dir: "packages/db", manifest: { name: "@mend/db", exports: {} } },
  ];
  const reaches = (path, text) =>
    findTestReaches({ files: new Map([[path, text]]), manifests, workflow: undefined });
  for (const [path, text] of [
    ["apps/api/src/a.ts", 'import { fixture } from "@mend/sessions/testing";'],
    ["apps/api/src/a.ts", 'const m = await import(/* why */ "@mend/sessions/testing");'],
    ["apps/api/src/a.ts", 'export { db } from "@mend/wild/fixtures/postgres";'],
    ["apps/api/src/a.ts", 'import "@mend/domain/src/removal.test.ts";'],
    ["apps/api/src/a.ts", 'import "../../../packages/domain/src/removal.test.ts";'],
    ["scripts/bundle.mjs", 'await import(/* fixture */ "../packages/db/test/postgres.ts");'],
    ["scripts/a.test.mjs", 'readFile(new URL("../packages/db/test/x.json", import.meta.url))'],
    ["scripts/a.mjs", 'readFile("/repo/packages/domain/src/../test/data.json")'],
    ["scripts/a.mjs", "// copies packages/db/test/postgres.ts beside the bundle"],
    ["Dockerfile", "COPY packages/sessions/test ./fixtures"],
    ["apps/mobile/package.json", '{ "scripts": { "check": "node ../../packages/db/test/x.mjs" } }'],
    ["package.json", '{ "files": ["packages/sessions/test"] }'],
  ]) {
    assert.equal(reaches(path, text).length, 1, `${path}: ${text}`);
  }
  for (const [path, text] of [
    ["apps/api/src/a.ts", 'import { a } from "@mend/sessions"; import "./testing/view.ts";'],
    ["apps/web/src/a.ts", 'const note = "packages/db/src/testing.ts packages/db/tests.ts";'],
    ["packages/domain/src/a.ts", "if (/^url\\./iu.test(entry.key)) return;"],
    [
      "packages/t3-contracts/t3code.pin.json",
      '{ "upstream": "packages/contracts/src/rpc.test.ts" }',
    ],
    [
      "packages/db/package.json",
      '{ "exports": { "./testing": "./test/x.ts" }, "scripts": { "test": "vitest ./test" } }',
    ],
  ]) {
    assert.deepEqual(reaches(path, text), [], `${path}: ${text}`);
  }
  // Tests may name tests: they are out of the warning's scope unless a lane job names them.
  for (const path of ["packages/sessions/test/a.test.ts", "apps/api/src/route.spec.tsx"]) {
    assert.ok(
      outOfScope.some(([skip]) => skip(path)),
      path,
    );
  }
  for (const path of [
    "apps/cli/test-fixtures/server.mjs",
    "apps/web/vite.config.ts",
    "Dockerfile",
  ]) {
    assert.ok(!outOfScope.some(([skip]) => skip(path)), path);
  }
  const fixture = "packages/sessions/test/fixtures/shell-profile/Dockerfile";
  const lane = (workflow) => findTestReaches({ files: new Map(), manifests, workflow });
  const packaging = "needs.changes.outputs.packaging != 'false'";
  assert.equal(
    lane({ jobs: { p: { if: packaging, steps: [{ run: `cat ${fixture}` }] } } }).length,
    1,
  );
  assert.equal(lane({ jobs: { p: { if: packaging, env: { F: fixture }, steps: [] } } }).length, 1);
  assert.equal(lane({ env: { F: fixture }, jobs: { p: { if: packaging, steps: [] } } }).length, 1);
  assert.deepEqual(
    lane({ jobs: { t: { if: "!cancelled()", steps: [{ run: `cat ${fixture}` }] } } }),
    [],
  );
});

test("the lanes' own test files are read, quoted or not", () => {
  const repo = [
    "scripts/a.test.mjs",
    "scripts/r.mjs",
    "scripts/bench/b.test.mjs",
    "scripts/o.test.mjs",
  ];
  const lanes = laneFilesOf(
    {
      jobs: {
        packaging: {
          if: "needs.changes.outputs.packaging != 'false'",
          steps: [
            {
              run: `node --test "scripts/a.test.mjs" --test-reporter=./scripts/r.mjs 'scripts/bench/*.test.mjs'`,
            },
          ],
        },
        other: { if: "!cancelled()", steps: [{ run: "node --test scripts/o.test.mjs" }] },
      },
    },
    (word) => repo.filter((path) => posix.matchesGlob(path, posix.normalize(word))),
  );
  assert.deepEqual([...lanes].toSorted(), repo.slice(0, 3).toSorted());
  const { laneFiles } = repository();
  for (const path of ["scripts/bundle-packaging.test.mjs", "scripts/remove-package-tests.mjs"]) {
    assert.ok(laneFiles.has(path), path);
  }
  assert.ok(
    [...laneFiles].some((path) => path.startsWith("scripts/bench/")),
    "globs expand",
  );
});
