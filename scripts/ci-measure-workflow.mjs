import { readFileSync, writeFileSync } from "node:fs";

import { parse, stringify } from "yaml";

/** Derive measurement jobs from production CI so setup, evidence and worker limits stay identical. */
export function measurementWorkflow(ci) {
  const jobs = structuredClone(ci.jobs);
  for (const job of Object.values(jobs)) {
    const checkout = job.steps.find((step) => step.uses?.startsWith("actions/checkout@"));
    // A job without a checkout (the `checks` gate reads only `needs`) has no ref to pin.
    if (checkout) checkout.with = { ...checkout.with, ref: "${{ inputs.head_sha }}" };
    // Fixtures exercise other events. Only the commands being measured receive this policy.
    for (const step of job.steps) {
      if (
        step.run === "node scripts/ci-turbo.mjs build typecheck lint" ||
        /^node scripts\/ci-shards\.mjs (engines|clients-a|clients-b)$/.test(step.run ?? "")
      ) {
        step.env = { ...step.env, CI_MEASUREMENT_CACHE: "${{ inputs.cache }}" };
      }
    }
  }
  // A dispatch must never satisfy the production required check on its workflow ref.
  jobs.checks.name = "measurement checks";
  const scope = jobs.changes.steps.find((step) => step.id === "scope");
  scope.env = { BASE_SHA: "${{ inputs.base_sha }}", HEAD_SHA: "${{ inputs.head_sha }}" };
  scope.run = `[[ "$BASE_SHA" =~ ^[a-f0-9]{40}$ && "$HEAD_SHA" =~ ^[a-f0-9]{40}$ ]]
[[ "$(git rev-parse HEAD)" == "$HEAD_SHA" ]]
git merge-base --is-ancestor "$BASE_SHA" "$HEAD_SHA"
node scripts/ci-scope.mjs "$BASE_SHA" "$HEAD_SHA" >> "$GITHUB_OUTPUT"`;
  return {
    name: "CI measurement",
    "run-name":
      "CI measurement · ${{ inputs.scenario }} · ${{ inputs.cache }} · ${{ inputs.head_sha }}",
    on: {
      workflow_dispatch: {
        inputs: {
          scenario: {
            description: "Scenario label",
            required: true,
            type: "choice",
            options: ["web", "docs", "sessions", "lockfile"],
          },
          cache: {
            description: "Cold disables remote; warm reads trusted main entries",
            required: true,
            type: "choice",
            options: ["cold", "warm"],
          },
          base_sha: {
            description: "Exact 40-character PR base SHA",
            required: true,
            type: "string",
          },
          head_sha: {
            description: "Exact 40-character scenario head SHA",
            required: true,
            type: "string",
          },
        },
      },
    },
    permissions: { contents: "read" },
    env: { TURBO_SCM_BASE: "${{ inputs.base_sha }}" },
    // Each dispatch is one independent observation. Never cancel a measured run.
    concurrency: { group: "ci-measurement-${{ github.run_id }}", "cancel-in-progress": false },
    jobs,
  };
}

if (import.meta.main) {
  const ci = parse(readFileSync(new URL("../.github/workflows/ci.yml", import.meta.url), "utf8"));
  writeFileSync(
    new URL("../.github/workflows/ci-measure.yml", import.meta.url),
    "# Generated by node scripts/ci-measure-workflow.mjs; CI tests reject drift.\n" +
      stringify(measurementWorkflow(ci), { lineWidth: 100 }),
  );
}
