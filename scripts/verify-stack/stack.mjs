/** The commit and tree a source names, and where git can archive the tree from. */
async function resolveSource(source) {
  if (source.kind === "pinned") return source;
  if (source.kind === "worktree") {
    const path = resolve(source.path.replace(/^~(?=\/)/, homedir()));
    const root = await gitOut(path, ["rev-parse", "--show-toplevel"]);
    const commit = await gitOut(root, ["rev-parse", "HEAD"]);
    // The working tree as a tree object, through a private index: the person's index, branch and
    // files are not touched. Untracked files count unless ignored, as `git status` shows them.
    const index = join(cacheDir, `index-${randomUUID()}`);
    const env = { ...process.env, GIT_INDEX_FILE: index };
    try {
      await git(root, ["read-tree", "HEAD"], { env });
      await git(root, ["add", "--all", "--", "."], { env });
      const tree = await gitOut(root, ["write-tree"], { env });
      const headTree = await gitOut(root, ["rev-parse", "HEAD^{tree}"]);
      return { ...source, path: root, gitDir: root, commit, tree, dirty: tree !== headTree };
    } finally {
      await rm(index, { force: true });
    }
  }
  const gitDir = join(cacheDir, "git", `${source.repository}.git`);
  if (!existsSync(join(gitDir, "HEAD"))) {
    await mkdir(gitDir, { recursive: true });
    await git(gitDir, ["init", "--bare", "--quiet"], { env: dockerEnv });
  }
  const { url } = REPOSITORIES[source.repository];
  // Into a ref of this fetch's own, not FETCH_HEAD: two starts sharing the cache each read back
  // the commit they fetched.
  const ref = `refs/verify-stack/${randomUUID()}`;
  await git(
    gitDir,
    ["fetch", "--quiet", "--no-tags", "--depth", "1", url, `+${fetchRefspec(source)}:${ref}`],
    { env: dockerEnv, timeout: 10 * 60_000, reason: true },
  ).catch((error) => {
    throw new CommandError(
      `--${source.repository} ${source.kind === "pr" ? `#${source.number}` : source.ref}: ${url} would not give it (${error.message})`,
    );
  });
  const commit = await gitOut(gitDir, ["rev-parse", ref], { env: dockerEnv });
  const tree = await gitOut(gitDir, ["rev-parse", `${ref}^{tree}`], { env: dockerEnv });
  return { ...source, gitDir, commit, tree };
}

/** The source tree as a directory, made once per tree: every build of it uses this context. */
async function contextOf(resolved) {
  const dir = join(cacheDir, "contexts", `${resolved.repository}-${resolved.tree}`);
  if (existsSync(dir)) return dir;
  const partial = `${dir}.partial-${randomUUID()}`;
  await mkdir(partial, { recursive: true });
  await new Promise((done, fail) => {
    const archive = spawn(
      "git",
      ["-C", resolved.gitDir, "archive", "--format=tar", resolved.tree],
      {
        env: process.env,
        stdio: ["ignore", "pipe", "inherit"],
      },
    );
    const untar = spawn("tar", ["-x", "-C", partial], { stdio: ["pipe", "inherit", "inherit"] });
    archive.stdout.pipe(untar.stdin);
    let pending = 2;
    const settle = (name) => (code) => {
      if (code !== 0) fail(new CommandError(`${name} of ${resolved.repository} failed (${code})`));
      else if (--pending === 0) done();
    };
    archive.once("close", settle("git archive"));
    untar.once("close", settle("tar"));
  });
  await rename(partial, dir);
  return dir;
}

