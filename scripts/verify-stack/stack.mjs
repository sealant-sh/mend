class CommandError extends Error {}

/**
 * Run a command. Output is captured, or appended to `log` when given (builds); `input` is written
 * to stdin. A failure names the command and its exit; its output is printed only for `log`ged
 * commands, which carry no secret (a build log), as the last lines of that log.
 */
function exec(command, args, options = {}) {
  const { env = dockerEnv, cwd, input, log, timeout = 30 * 60_000, stdio, reason } = options;
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, args, {
      cwd,
      env,
      stdio: stdio ?? [input === undefined ? "ignore" : "pipe", "pipe", "pipe"],
    });
    const out = [];
    const err = [];
    const sink = log ? createWriteStream(log, { flags: "a" }) : null;
    child.stdout?.on("data", (chunk) => (sink ? sink.write(chunk) : out.push(chunk)));
    child.stderr?.on("data", (chunk) => (sink ? sink.write(chunk) : err.push(chunk)));
    const timer = setTimeout(() => child.kill("SIGKILL"), timeout);
    child.once("error", (error) => {
      clearTimeout(timer);
      reject(new CommandError(`${command} could not start: ${error.message}`));
    });
    child.once("close", async (code, signal) => {
      clearTimeout(timer);
      if (sink) await new Promise((done) => sink.end(done));
      const stdout = Buffer.concat(out).toString();
      const stderr = Buffer.concat(err).toString();
      if (code === 0) return resolvePromise({ stdout, stderr });
      let tail = "";
      if (log) {
        const lines = (await readFile(log, "utf8").catch(() => "")).trimEnd().split("\n");
        tail = `\n${lines.slice(-30).join("\n")}\n(full log: ${log})`;
      }
      const ended = signal ? `signal ${signal}` : `exit ${code}`;
      // The verb, not a flag or a path; and, when the caller asks, the command's own last word on
      // why (only for commands whose output carries no secret, such as an anonymous fetch).
      const verb = args.find((arg) => !arg.startsWith("-") && !arg.startsWith("/")) ?? "";
      const why = reason ? `: ${stderr.trim().split("\n").at(-1) ?? ""}` : "";
      reject(new CommandError(`${command} ${verb} failed (${ended})${why}${tail}`));
    });
    if (input !== undefined) child.stdin.end(input);
  });
}

const docker = (args, options) => exec("docker", args, options);
const dockerOut = async (args, options) => (await docker(args, options)).stdout.trim();
const git = (repo, args, options = {}) =>
  exec("git", ["-C", repo, ...args], { env: options.env ?? process.env, ...options });
const gitOut = async (repo, args, options) => (await git(repo, args, options)).stdout.trim();

const say = (line) => process.stdout.write(`${line}\n`);
const since = (start) => (Date.now() - start) / 1000;
const pause = (ms) => new Promise((done) => setTimeout(done, ms));

async function timed(record, name, work) {
  const start = Date.now();
  const result = await work();
  record[name] = Math.round(since(start) * 10) / 10;
  return result;
}

