/** The daemon-side path of its own socket, which the inner Mend container mounts. */
async function daemonSocket() {
  const info = JSON.parse(await dockerOut(["info", "--format", "{{json .}}"]));
  const rootless = (info.SecurityOptions ?? []).some((option) => option.includes("rootless"));
  // A rootless daemon (a session's sidecar) listens at $XDG_RUNTIME_DIR/docker.sock of its user;
  // its runtime directory is the daemon's own `/run/user/<uid>`.
  if (rootless) {
    const runtime = await dockerOut([
      "run",
      "--rm",
      "--network",
      "none",
      "--volume",
      "/run/user:/host-run-user:ro",
      "--entrypoint",
      "sh",
      FIXTURE_BASE_IMAGE,
      "-c",
      "ls /host-run-user/*/docker.sock",
    ]);
    const socket = runtime.split("\n")[0]?.replace("/host-run-user", "/run/user");
    if (!socket)
      throw new CommandError("the rootless daemon's socket was not found under /run/user");
    return { rootless, socket };
  }
  return { rootless, socket: "/var/run/docker.sock" };
}

// ─── up ─────────────────────────────────────────────────────────────────────

/**
 * The relay's port, and so the browser origin's: not 3105, where Mend's own dev server listens when
 * a session runs `pnpm dev` (apps/web/vite.config.ts), since Mend dials the workspace loopback
 * before the Docker sidecar.
 */
const DEFAULT_PORT = 3305;

/** The inner server publishes its web port this far above the relay's. */
const SERVER_PORT_OFFSET = 10_000;

function parseFlags(args) {
  const flags = {
    port: DEFAULT_PORT,
    check: true,
    json: false,
    purge: false,
    force: false,
    keep: false,
  };
  const sources = {};
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    const value = () => {
      if (i + 1 >= args.length) throw new Error(`${arg} needs a value`);
      return args[++i];
    };
    if (arg === "--mend" || arg === "--sealant" || arg === "--sealantd")
      sources[arg.slice(2)] = value();
    else if (arg === "--port") flags.port = Number(value());
    else if (arg === "--no-check") flags.check = false;
    else if (arg === "--json") flags.json = true;
    else if (arg === "--purge") flags.purge = true;
    else if (arg === "--force") flags.force = true;
    else if (arg === "--keep") flags.keep = true;
    else throw new Error(`unknown option ${arg}`);
  }
  if (!Number.isInteger(flags.port) || flags.port < 1024 || flags.port + SERVER_PORT_OFFSET > 65535)
    throw new Error(`--port takes a port between 1024 and ${65535 - SERVER_PORT_OFFSET}`);
  return { flags, sources };
}

/** Refuse a daemon that runs a Mend server the stack did not make: its names are the same. */
async function assertDaemonIsFree() {
  const volumes = (await dockerOut(["volume", "ls", "--quiet"])).split("\n").filter(Boolean);
  const product = ["mend-store", "mend-control", "mend-garage"].filter((v) => volumes.includes(v));
  const compose = await dockerOut([
    "ps",
    "--all",
    "--quiet",
    "--filter",
    `label=com.docker.compose.project=${COMPOSE_PROJECT}`,
  ]);
  if (volumes.includes(STATE_VOLUME))
    throw new Error(
      "a verify stack is already up on this daemon: `report` reads it, `down` removes it",
    );
  if (product.length > 0 || compose !== "")
    throw new Error(
      "this Docker daemon runs a Mend server of its own (Compose project mend or its volumes): the stack uses the same names, so it refuses. Run it in a Mend session, or point DOCKER_HOST at an empty daemon.",
    );
}

/**
 * Claim the daemon for this start before anything is built (lifecycle.mjs): of two starts at once,
 * one holds the claim and the other is refused, so they never share names or state.
 */
async function claimDaemon(claimId) {
  if (!(await claim(dockerOut, { claimId, image: FIXTURE_BASE_IMAGE })))
    throw new Error(
      "a verify stack is already starting or up on this daemon: `report` reads it, `down` removes it",
    );
}

/**
 * Build, install and check a stack. `claimId` names this start's claim; `serve` passes the one its
 * watchdog guards. Everything that can fail after the claim runs inside the cleanup below, which
 * removes this start's stack and nobody else's (`--keep` leaves it for a look).
 */
async function up(args, { claimId = randomUUID() } = {}) {
  const { flags, sources: specs } = parseFlags(args);
  if (insideCaptureRoot(cacheDir))
    throw new Error(
      `${cacheDir} is inside a capture root: the stack's files would be saved with the session. Set MEND_VERIFY_STACK_CACHE outside /workspace.`,
    );
  await mkdir(cacheDir, { recursive: true, mode: 0o700 });
  await mkdir(dockerEnv.DOCKER_CONFIG, { recursive: true, mode: 0o700 });
  await mkdir(dockerEnv.HOME, { recursive: true, mode: 0o700 });
  const started = Date.now();
  const phases = {};
  const runId = new Date().toISOString().replace(/[:.]/g, "-");
  const logs = join(cacheDir, "logs", runId);

  await docker(["version", "--format", "{{.Server.Version}}"]).catch(() => {
    throw new Error(
      "no Docker daemon answers: in a session, turn on the project's Docker service (Settings · workspace image)",
    );
  });
  await assertDaemonIsFree();
  // The base of the fixture's sessions, and the image the claim and the socket probe run.
  await docker(["pull", "--quiet", FIXTURE_BASE_IMAGE], { timeout: 15 * 60_000 });
  // Before the claim, so a trim that trips cannot strand one.
  await trimCaches();
  await mkdir(logs, { recursive: true });
  await claimDaemon(claimId);
  try {
    return await upClaimed(flags, specs, { started, phases, logs });
  } catch (error) {
    if (flags.keep) throw error;
    say("verify stack · up failed; removing what it made (--keep keeps it for a look)");
    await removeStack({ claimId }).catch((cleanup) =>
      say(`verify stack · removing it failed: ${cleanup.message}`),
    );
    throw error;
  }
}

async function upClaimed(flags, specs, { started, phases, logs }) {
  const repos = await sessionRepos();
  const parsed = Object.fromEntries(
    Object.keys(REPOSITORIES).map((repository) => [
      repository,
      parseSource(
        repository,
        specs[repository] ?? defaultSpec(repository, { mendRoot, sessionRepos: repos }),
      ),
    ]),
  );
  say("verify stack · resolving sources");
  const resolved = await timed(phases, "sources", async () =>
    Object.fromEntries(
      await Promise.all(
        Object.entries(parsed).map(async ([name, source]) => [name, await resolveSource(source)]),
      ),
    ),
  );
  for (const source of Object.values(resolved)) say(`  ${describeSource(source)}`);

  const contexts = await timed(phases, "contexts", async () =>
    Object.fromEntries(
      await Promise.all(
        Object.entries(resolved)
          .filter(([, source]) => source.kind !== "pinned")
          .map(async ([name, source]) => [name, await contextOf(source)]),
      ),
    ),
  );
  const cliVersion = JSON.parse(await showFile(resolved.mend, "apps/cli/package.json")).version;
  const composeYaml = await showFile(resolved.mend, "deploy/docker/compose.v2.yaml");
  const relay = relayEndpoint(process.env.DOCKER_HOST, flags.port);
  const { socket, rootless } = await daemonSocket();

  // Every build starts at once. The bundle copies Core's three images in, so it waits for them;
  // it only names the sealantd image (the bundled worker bakes it into workspace images when an
  // inner session first launches), so sealantd's cargo build runs on beside the bundle and the
  // install, and the stack is ready once it is done too.
  say("verify stack · building images (logs: " + logs + ")");
  await ensureBuildx();
  const outcomes = {};
  const upstream = imageNames(resolved, { cliVersion, upstreamIds: [] });
  const component = async (name, work) => {
    const outcome = await timed(phases, `build:${name}`, work);
    outcomes[name] = outcome;
    say(`  ${name} · ${outcome} · ${formatSeconds(phases[`build:${name}`])}`);
  };
  const sealantdBuild =
    upstream.sealantd === null
      ? Promise.resolve()
      : component("sealantd", () =>
          build(logs, "sealantd", {
            context: contexts.sealantd,
            dockerfile: "docker/Dockerfile",
            tag: upstream.sealantd,
            labels: { [`${STACK_LABEL}.source`]: `sealantd@${resolved.sealantd.commit}` },
          }),
        );

  const coreBuilds =
    upstream.sealantApi === null
      ? []
      : [
          ["api", upstream.sealantApi],
          ["worker", upstream.sealantWorker],
          ["ssh-gateway", upstream.sealantSshGateway],
        ].map(([app, tag]) =>
          component(`sealant-${app}`, () =>
            build(logs, `sealant-${app}`, {
              context: contexts.sealant,
              dockerfile: `apps/${app}/Dockerfile`,
              tag,
              labels: { [`${STACK_LABEL}.source`]: `sealant@${resolved.sealant.commit}` },
            }),
          ),
        );
  const cliBuild = component("mend-cli", () =>
    build(logs, "mend-cli", {
      context: contexts.mend,
      dockerfile: { text: CLI_DOCKERFILE },
      tag: upstream.cli,
    }),
  );
  // Both are awaited below; a failure before then is not an unhandled rejection.
  for (const pending of [sealantdBuild, cliBuild]) pending.catch(() => undefined);
  const pulls = timed(phases, "pulls", () =>
    Promise.all(
      composeImages(composeYaml).map((image) =>
        docker(["pull", "--quiet", image], { timeout: 15 * 60_000 }),
      ),
    ),
  );
  await Promise.all([...coreBuilds, pulls]);
  // sealantd by its tree (its tag), Core by the image ids the bundle copies.
  const upstreamIds = [
    resolved.sealantd.kind === "pinned" ? "pinned" : resolved.sealantd.tree,
    ...(await Promise.all(
      [upstream.sealantApi, upstream.sealantWorker, upstream.sealantSshGateway].map((tag) =>
        tag === null ? "pinned" : imageId(tag),
      ),
    )),
  ];
  const images = imageNames(resolved, { cliVersion, upstreamIds });
  const bundleBuild = component("mend", () =>
    build(logs, "mend", {
      context: contexts.mend,
      dockerfile: "Dockerfile",
      tag: images.mend,
      args: mendBuildArgs(images),
      labels: { [`${STACK_LABEL}.source`]: `mend@${resolved.mend.commit}` },
    }),
  );
  await Promise.all([cliBuild, bundleBuild]);

  // Setup: the product's own install, run where its files are the daemon's files.
  const origins = innerOrigins(relay);
  const state = {
    version: 1,
    createdAt: new Date(started).toISOString(),
    sources: Object.fromEntries(
      Object.entries(resolved).map(([name, source]) => [
        name,
        source.kind === "pinned"
          ? { kind: "pinned" }
          : {
              kind: source.kind,
              ...(source.kind === "pr" ? { number: source.number } : {}),
              ...(source.kind === "ref" ? { ref: source.ref } : {}),
              ...(source.kind === "worktree" ? { path: source.path, dirty: source.dirty } : {}),
              commit: source.commit,
              tree: source.tree,
              description: describeSource(source),
            },
      ]),
    ),
    images,
    builds: outcomes,
    relay,
    url: origins.url,
    dockerSocket: socket,
    rootless,
    phases,
    logs,
  };
  await writeState(state);
  say(`verify stack · mend server setup ${images.version}`);
  await docker(["volume", "create", "--label", `${STACK_LABEL}=1`, STATE_VOLUME]);
  await timed(phases, "setup", async () => {
    const setup = cliRun(
      state,
      [
        "server",
        "setup",
        "--docker-socket",
        socket,
        "--version",
        images.version,
        "--assets-dir",
        ASSETS_DIR,
        "--offline",
        // The server's own port, on the daemon's loopback: setup's check and the relay go through
        // the relay's port, and a rootless daemon cannot publish one port on loopback and on
        // every interface at once.
        "--port",
        String(flags.port + SERVER_PORT_OFFSET),
        "--ssh-port",
        "2222",
        "--url",
        origins.url,
        ...origins.extra.flatMap((origin) => ["--origin", origin]),
      ],
      { home: "server", log: join(logs, "setup.log") },
    );
    // Setup waits for health at --url, which the relay serves: the relay joins the Compose
    // network as soon as setup has made it.
    const relayed = (async () => {
      for (let i = 0; i < 600; i++) {
        const network = await docker(["network", "inspect", COMPOSE_NETWORK]).then(
          () => true,
          () => false,
        );
        if (network) return startRelay(state);
        await pause(500);
      }
      throw new CommandError(`setup never made the ${COMPOSE_NETWORK} network`);
    })();
    await Promise.all([setup, relayed]);
  });
  say(`  setup · ${formatSeconds(phases.setup)}`);

  await timed(phases, "account", () => firstAccount(state));
  await timed(phases, "fixture", () => fixtureProject(state, contexts.mend));
  // Inner sessions need it: their workspace images are built from it.
  await sealantdBuild;
  phases.ready = Math.round(since(started) * 10) / 10;
  state.readyAt = new Date().toISOString();
  await writeState(state);
  say(`verify stack · ready in ${formatSeconds(phases.ready)} · ${origins.url}`);
  if (flags.check) await check(state);
  await writeState(state);
  return state;
}

async function startRelay(state) {
  // A TCP relay on the Compose network: the browser origin's port, published where the session
  // reaches this daemon, to the inner web. Each connection is piped; nothing is read or kept.
  const code = [
    'const net = require("node:net");',
    "net.createServer((c) => {",
    `  const u = net.connect(${INNER_WEB_PORT}, "mend");`,
    "  c.pipe(u); u.pipe(c);",
    '  c.on("error", () => u.destroy()); u.on("error", () => c.destroy());',
    `}).listen(${INNER_WEB_PORT}, "0.0.0.0");`,
  ].join("\n");
  await docker([
    "run",
    "--detach",
    "--name",
    RELAY_CONTAINER,
    "--label",
    `${STACK_LABEL}=1`,
    "--restart",
    "unless-stopped",
    "--network",
    COMPOSE_NETWORK,
    "--publish",
    state.relay.publish,
    "--entrypoint",
    "node",
    state.images.cli,
    "-e",
    code,
  ]);
}

const relayOrigin = (state) => `http://${state.relay.host}:${state.relay.port}`;

/** The inner server's first account: generated password, kept in the state volume only. */
async function firstAccount(state) {
  const password = randomBytes(32).toString("hex");
  const response = await fetch(`${relayOrigin(state)}/api/auth/sign-up/email`, {
    method: "POST",
    headers: { origin: state.url, "content-type": "application/json" },
    body: JSON.stringify({ email: INNER_ACCOUNT_EMAIL, password, name: "Verifier" }),
    signal: AbortSignal.timeout(60_000),
  });
  await response.body?.cancel();
  const token = response.headers.get("set-auth-token");
  if (!response.ok || !token)
    throw new CommandError(`the inner server refused the first account (HTTP ${response.status})`);
  // The CLI's own configuration, as `mend login` writes it; the inner CLI reads it.
  await writePrivate(
    state,
    "client/.config/mend/cli.json",
    JSON.stringify({ url: state.url, token, deviceId: randomUUID() }),
  );
  await writePrivate(
    state,
    "client/.config/mend-verify-stack/account.json",
    JSON.stringify({ email: INNER_ACCOUNT_EMAIL, password }),
  );
}

async function innerToken(state) {
  return JSON.parse(await readPrivate(state, "client/.config/mend/cli.json")).token;
}

async function innerApi(state, route, { method = "GET", body } = {}) {
  const token = await innerToken(state);
  const response = await fetch(`${relayOrigin(state)}/api${route}`, {
    method,
    headers: {
      authorization: `Bearer ${token}`,
      ...(body === undefined ? {} : { "content-type": "application/json" }),
    },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    signal: AbortSignal.timeout(60_000),
  });
  if (!response.ok) {
    await response.body?.cancel();
    throw new CommandError(`inner API ${method} ${route.split("?")[0]}: HTTP ${response.status}`);
  }
  return response.json();
}

