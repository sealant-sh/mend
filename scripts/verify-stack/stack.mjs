/** `mend run -- true` on the inner Sealant: the stack launches a session end to end. */
async function check(state) {
  say("verify stack · check · inner mend run -- true");
  const started = Date.now();
  const name = `check-${Date.now().toString(36)}`;
  await cliRun(state, ["run", "--project", FIXTURE_PROJECT, "--name", name, "--", "true"], {
    timeout: 15 * 60_000,
    log: join(state.logs, `${name}.log`),
  });
  const projects = await innerApi(state, "/projects");
  const project = projects.find((item) => item.name === FIXTURE_PROJECT);
  const detail = await innerApi(state, `/projects/${project.id}?deadEnds=include`);
  const session = detail.sessions?.find((item) => item.branch === `mend/${name}`);
  // `mend run` returns once the command exits; the session settles after its Stop saves.
  let status = null;
  if (session !== undefined) {
    const settleBy = Date.now() + 180_000;
    while (Date.now() < settleBy) {
      status = (await innerApi(state, `/sessions/${session.id}`)).session.status;
      if (status === "completed" || status === "failed" || status === "stopped") break;
      await pause(1000);
    }
  }
  state.check = {
    command: "mend run -- true",
    session: session?.id ?? null,
    status,
    seconds: Math.round(since(started) * 10) / 10,
    at: new Date().toISOString(),
  };
  say(
    `  inner session ${session?.id.slice(0, 8) ?? "?"} · ${status ?? "not found"} · ${formatSeconds(state.check.seconds)}`,
  );
  if (status !== "completed")
    throw new CommandError(`the inner session ended ${status ?? "unseen"}, not completed`);
}

// ─── report ─────────────────────────────────────────────────────────────────

/** What every process of this daemon holds: PSS summed from a probe in its process namespace. */
async function measureMemory(state) {
  if (state.rootless) {
    // A rootless daemon's process namespace is the session sidecar's: every process there is the
    // stack's (dockerd, containerd, the inner server, its sessions). Privileged inside the user
    // namespace only, so the probe reads every process's smaps.
    const text = await dockerOut(
      [
        "run",
        "--rm",
        "--privileged",
        "--pid",
        "host",
        "--network",
        "none",
        "--entrypoint",
        "sh",
        state.images.mend,
        "-c",
        MEMORY_PROBE,
      ],
      { timeout: 120_000 },
    );
    const memory = parseMemory(text);
    return { method: "pss of every process of the session's Docker daemon", ...memory };
  }
  // Any other daemon is shared with the machine: the stack's containers only, as Docker counts.
  const ids = await stackContainers();
  if (ids.length === 0) return { method: "docker stats", totalKb: 0, processes: [] };
  const lines = await dockerOut([
    "stats",
    "--no-stream",
    "--format",
    "{{.Name}} {{.MemUsage}}",
    ...ids,
  ]);
  const unit = { B: 1 / 1024, KiB: 1, MiB: 1024, GiB: 1024 * 1024 };
  const processes = lines.split("\n").map((line) => {
    const [name, usage] = line.split(" ");
    const match = /^([\d.]+)(B|KiB|MiB|GiB)$/.exec(usage ?? "");
    return { command: name, kb: match ? Math.round(Number(match[1]) * unit[match[2]]) : 0 };
  });
  return {
    method: "docker stats of the stack's containers",
    totalKb: processes.reduce((sum, item) => sum + item.kb, 0),
    processes,
  };
}

async function inspectAll(ids) {
  if (ids.length === 0) return [];
  return JSON.parse(await dockerOut(["inspect", ...ids]));
}

/** Every container of the stack: its own, the inner server's, and the inner sessions'. */
async function stackContainers() {
  const ids = (await dockerOut(["ps", "--all", "--quiet", "--no-trunc"]))
    .split("\n")
    .filter(Boolean);
  const containers = await inspectAll(ids);
  return containers
    .filter(
      (item) =>
        item.Config?.Labels?.[STACK_LABEL] === "1" ||
        item.Config?.Labels?.["com.docker.compose.project"] === COMPOSE_PROJECT ||
        isSealantExecutor(item) ||
        /^\/sealant-[0-9a-f-]+-docker$/i.test(item.Name ?? ""),
    )
    .map((item) => item.Id);
}

async function report(args) {
  const { flags } = parseFlags(args);
  const state = await readState();
  if (!state) throw new Error("no verify stack here: `up` starts one");
  const memory = await measureMemory(state);
  const isolation = isolationFindings(await inspectAll(await stackContainers()), outerSecrets);
  state.memory = {
    at: new Date().toISOString(),
    method: memory.method,
    totalKb: memory.totalKb,
    top: memory.processes.slice(0, 12),
  };
  state.isolation = {
    checked: outerSecrets.length,
    findings: isolation,
  };
  await writeState(state);
  if (flags.json) return say(JSON.stringify(state, null, 2));
  say("verify stack");
  for (const source of Object.values(state.sources))
    say(`  ${source.description ?? "pinned (the release Mend pins)"}`);
  say(`  web · ${state.url} (from the session: ${relayOrigin(state)})`);
  for (const [phase, seconds] of Object.entries(state.phases))
    say(`  ${phase.padEnd(22)} ${formatSeconds(seconds)}`);
  if (state.check)
    say(
      `  check: ${state.check.command} · ${state.check.status} · ${formatSeconds(state.check.seconds)}`,
    );
  say(`  memory · ${formatKb(memory.totalKb)} · ${memory.method}`);
  for (const item of memory.processes.slice(0, 8))
    say(`    ${formatKb(item.kb).padStart(9)}  ${item.command}`);
  // What was looked at, and only that: each container's environment, command and labels.
  say(
    outerSecrets.length === 0
      ? "  isolation · not checked: no credential of the session is readable here"
      : isolation.length === 0
        ? `  isolation · the session's credential (${outerSecrets.length} value(s)) is in no container's environment, command or labels`
        : `  isolation · FOUND in ${isolation.join(", ")}`,
  );
  if (isolation.length > 0) process.exitCode = 1;
}

// ─── down ───────────────────────────────────────────────────────────────────

async function down(args) {
  const { flags } = parseFlags(args);
  const owner = await currentClaim(dockerOut);
  const volumes = (await dockerOut(["volume", "ls", "--quiet"])).split("\n").filter(Boolean);
  const present = owner.state === "present" || volumes.includes(STATE_VOLUME);
  if (!present && !flags.force && !flags.purge)
    throw new Error("no verify stack on this daemon (--force sweeps what one left anyway)");
  let removed = { containers: 0, volumes: 0 };
  if (present || flags.force) removed = await removeStack();
  if (flags.purge) await purgeCaches();
  say(
    `verify stack · removed ${removed.containers} container(s), ${removed.volumes} volume(s)${flags.purge ? "; images, build cache and every cache directory purged" : "; images kept for the next up"}`,
  );
}

/**
 * Remove the stack on this daemon. With `claimId`, only when the daemon's current owner carries
 * that claim, and null (nothing touched) when it does not: a start or a watchdog removes its own
 * stack and never another's. The owner container goes last, by its id, so until everything else is
 * gone a new start is still refused.
 */
async function removeStack({ claimId = null } = {}) {
  const owner = await currentClaim(dockerOut);
  if (claimId !== null && (owner.state !== "present" || owner.claim !== claimId)) return null;
  const ownerId = owner.state === "present" ? owner.id : null;
  const ids = (await stackContainers()).filter((id) => id !== ownerId);
  if (ids.length > 0) await docker(["rm", "--force", "--volumes", ...ids]);
  const volumes = (await dockerOut(["volume", "ls", "--quiet"])).split("\n").filter(Boolean);
  const owned = [
    STATE_VOLUME,
    FIXTURE_VOLUME,
    "mend-store",
    "mend-control",
    "mend-garage",
    ...volumes.filter((name) => name.startsWith(`${COMPOSE_PROJECT}_`)),
  ].filter((name) => volumes.includes(name));
  if (owned.length > 0) await docker(["volume", "rm", "--force", ...owned]);
  const networks = (await dockerOut(["network", "ls", "--format", "{{.Name}}"]))
    .split("\n")
    .filter((name) => name === COMPOSE_NETWORK || /^sealant-[0-9a-f-]+-network$/i.test(name));
  for (const network of networks) await docker(["network", "rm", network]).catch(() => undefined);
  if (ownerId !== null) await docker(["rm", "--force", ownerId]);
  await rm(stateFile, { force: true });
  return { containers: ids.length + (ownerId === null ? 0 : 1), volumes: owned.length };
}

/**
 * Everything the stack keeps for its next start: its images, BuildKit's cache on this daemon (layers
 * and cache mounts, cargo's included), and its cache directories (contexts, packed packages, the
 * bare repositories, logs). Works with or without a stack up.
 */
async function purgeCaches() {
  const images = (await dockerOut(["image", "ls", "--quiet", "--filter", `label=${STACK_LABEL}=1`]))
    .split("\n")
    .filter(Boolean);
  if (images.length > 0)
    await docker(["image", "rm", "--force", ...new Set(images)]).catch(() => undefined);
  await ensureBuildx();
  await docker(["buildx", "prune", "--all", "--force"]);
  for (const dir of ["contexts", "packages", "git", "logs"])
    await rm(join(cacheDir, dir), { recursive: true, force: true });
}

/** How many entries each cache directory keeps across starts; older ones go at the next `up`. */
const RETENTION = { contexts: 6, packages: 6, logs: 10 };

async function trimCaches() {
  for (const [dir, keep] of Object.entries(RETENTION)) {
    const root = join(cacheDir, dir);
    const entries = [];
    for (const name of await readdir(root).catch(() => [])) {
      // An entry that vanished or cannot be read is skipped, not fatal: trimming is housekeeping.
      const info = await lstat(join(root, name)).catch(() => null);
      if (info !== null) entries.push({ name, mtimeMs: info.mtimeMs });
    }
    for (const name of beyondRetention(entries, keep))
      await rm(join(root, name), { recursive: true, force: true }).catch((error) =>
        say(`verify stack · could not trim ${dir}/${name}: ${error.message}`),
      );
  }
}

// ─── serve ──────────────────────────────────────────────────────────────────

/**
 * `up`, then hold while the Service runs. The Service's port is the relay's: Mend dials the
 * workspace loopback, then the Docker sidecar.
 *
 * The stack goes when this process goes, however it goes. Mend stops a Service by hanging up its
 * terminal (SIGHUP to the process group, SIGKILL two seconds later, sealantd `sealant-pty` close),
 * a verifier may be killed outright, and `up` may fail. So the teardown does not run here: a
 * watchdog in a session of its own, out of the group's reach, guards this start's claim
 * (lifecycle.mjs `watch`). It starts before the claim, so no moment exists in which a claim is
 * made and nobody would remove it; it waits for this process to end, and then removes the stack
 * only if the daemon's owner is still this start's claim. A start that ends holding no claim stops
 * its watchdog.
 */
async function serve(args) {
  const claimId = randomUUID();
  const watcher = startWatchdog(claimId);
  for (const signal of ["SIGHUP", "SIGTERM", "SIGINT"]) process.on(signal, () => process.exit(0));
  let state;
  try {
    state = await up(args, { claimId });
  } catch (error) {
    // A start that holds no claim now (refused, or its own cleanup removed it) has nothing for a
    // watchdog to guard: it goes too. One that may still hold one, or whose lookup failed, keeps
    // it, and it finishes the job.
    const owner = await currentClaim(dockerOut).catch(() => null);
    if (owner !== null && !(owner.state === "present" && owner.claim === claimId)) {
      try {
        process.kill(watcher.pid, "SIGTERM");
      } catch {
        // Already gone.
      }
    }
    throw error;
  }
  say(
    `verify stack · on your machine: mend service connect stack --port ${state.relay.port}, then open ${state.url}`,
  );
  say(
    "verify stack · sign in: node scripts/verify-stack/stack.mjs mend invite --role owner --days 1",
  );
  let last = null;
  for (;;) {
    const healthy = await fetch(`${relayOrigin(state)}/api/health`, {
      signal: AbortSignal.timeout(5000),
    }).then(
      (response) => response.ok,
      () => false,
    );
    if (healthy !== last) say(`verify stack · health ${healthy ? "answers" : "does not answer"}`);
    last = healthy;
    await pause(30_000);
  }
}

/**
 * A running process's start time (field 22 of /proc/<pid>/stat), so a reused pid is not mistaken
 * for it; null once it has ended, a zombie (state Z) included: nothing may have reaped it yet.
 */
const startTimeOf = (pid) => {
  try {
    const line = readFileSync(`/proc/${pid}/stat`, "utf8");
    const fields = line.slice(line.lastIndexOf(")") + 2).split(" ");
    if (fields[0] === "Z" || fields[0] === "X") return null;
    return fields[19] ?? null;
  } catch {
    return null;
  }
};

function startWatchdog(claimId) {
  const log = join(cacheDir, "logs", "watchdog.log");
  mkdirSync(dirname(log), { recursive: true });
  const out = openSync(log, "a");
  const started = startTimeOf(process.pid) ?? "";
  const child = spawn(
    process.execPath,
    [fileURLToPath(import.meta.url), "watchdog", String(process.pid), started, claimId],
    { detached: true, stdio: ["ignore", out, out], env: process.env },
  );
  child.unref();
  say(`verify stack · watchdog holds the stack to this process (log: ${log})`);
  return child;
}

/** `watchdog <pid> <start time> <claim id>`: lifecycle.mjs `watch` for that process and claim. */
async function watchdog([pid, started, claimId]) {
  if (!claimId) throw new Error("watchdog needs the claim id it guards");
  const log = (line) => say(`${new Date().toISOString()} verify stack · ${pid} · ${line}`);
  const outcome = await watch({
    docker: dockerOut,
    alive: () => {
      const now = startTimeOf(pid);
      return now !== null && (started === "" || now === started);
    },
    claimId,
    takeDown: async () => {
      const removed = await removeStack({ claimId });
      if (removed !== null)
        log(`removed ${removed.containers} container(s), ${removed.volumes} volume(s)`);
    },
    pause,
    now: Date.now,
    log,
  });
  log(
    {
      "taken-down": "the stack is down",
      "not-ours": "the daemon's claim is another start's; nothing touched",
      "never-claimed": "this start never held a claim; nothing touched",
    }[outcome],
  );
}

