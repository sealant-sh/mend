/**
 * Where this daemon's ledger lives: what the stack made on it, by exact identity, one file per
 * recording window, under `<cache>/ledger/<daemon>/` (the daemon as the lock names it), so a
 * teardown of one daemon never reads or removes another's. Each directory is checked as the lock's
 * is (`privateDirectory`). A teardown removes only entries that also have the stack's shape
 * (lib.mjs `planTeardown`).
 */
async function ledgerDirectory() {
  privateDirectory(join(cacheDir, "ledger"));
  return privateDirectory(join(cacheDir, "ledger", await daemonKey()));
}

/**
 * The daemon's containers (id, name, Compose project) and networks (id, name), and its volumes by
 * name and creation time. Retried when something goes between its listing and its inspection.
 */
async function snapshot() {
  const rows = (output) => nonEmptyLines(output).map((line) => line.split("\t"));
  for (let attempt = 0; ; attempt++) {
    try {
      const names = nonEmptyLines(await dockerOut(["volume", "ls", "--quiet"]));
      const volumes =
        names.length === 0
          ? []
          : rows(
              await dockerOut([
                "volume",
                "inspect",
                "--format",
                "{{.Name}}\t{{.CreatedAt}}",
                ...names,
              ]),
            ).map(([name, createdAt]) => ({ name, createdAt }));
      const containers = rows(
        await dockerOut([
          "ps",
          "--all",
          "--no-trunc",
          "--format",
          '{{.ID}}\t{{.Names}}\t{{.Label "com.docker.compose.project"}}',
        ]),
      ).map(([id, name, compose = ""]) => ({ id, name, compose }));
      const networks = rows(
        await dockerOut(["network", "ls", "--no-trunc", "--format", "{{.ID}}\t{{.Name}}"]),
      ).map(([id, name]) => ({ id, name }));
      return { containers, networks, volumes };
    } catch (error) {
      if (attempt >= 4) throw error;
      await pause(500);
    }
  }
}

async function writeAtomically(file, value) {
  await writeFile(`${file}.tmp`, `${JSON.stringify(value)}\n`, { mode: 0o600 });
  await rename(`${file}.tmp`, file);
}

/**
 * Run `work` as a recording window: what appears on the daemon while it runs and has the window's
 * `shape` (lib.mjs `SHAPES`: `install` for `up`, `session` for `mend` and `check`) is the stack's.
 * The session's daemon is shared with its agent and its person, so anything else that appears
 * meanwhile (a dev database, say) is not recorded. The window's file is written when it opens,
 * every two seconds while it runs and once more when it ends, so a window cut short by a kill has
 * recorded all but its last seconds and says so (`closed: false`). When `state` is given, the whole
 * ledger is also copied into the state volume, for a `down` run without this cache directory.
 */
async function recording(work, { state = null, shape = SHAPES.session } = {}) {
  const dir = await ledgerDirectory();
  const window = { window: randomUUID(), startedAt: new Date().toISOString() };
  const file = join(dir, `${window.window}.json`);
  const before = await snapshot();
  let made = madeSince(before, before, shape);
  const save = (closed) => writeAtomically(file, { ...window, closed, ...made });
  await save(false);
  const ticker = { open: true, wake: () => undefined };
  const ticks = (async () => {
    for (;;) {
      await new Promise((done) => {
        ticker.wake = done;
        setTimeout(done, 2000);
      });
      if (!ticker.open) return;
      try {
        made = madeSince(before, await snapshot(), shape);
        await save(false);
      } catch {
        // The next tick, or the close, records it.
      }
    }
  })();
  try {
    return await work();
  } finally {
    ticker.open = false;
    ticker.wake();
    await ticks;
    try {
      made = madeSince(before, await snapshot(), shape);
      await save(true);
    } catch (error) {
      say(
        `verify stack · the ledger's last record failed (${error.message}): it keeps what the recording saw until then, marked as cut short`,
      );
    }
    if (state !== null) {
      const ledger = mergeLedgers((await readLedgerFiles()).windows);
      await writePrivate(state, "ledger.json", JSON.stringify(ledger)).catch(() => undefined);
    }
  }
}

/** A ledger file: this user's own regular file, private to them, read without following a link. */
function readPrivateFile(path) {
  const fd = openSync(path, constants.O_RDONLY | constants.O_NOFOLLOW);
  try {
    const file = fstatSync(fd);
    if (!file.isFile() || file.uid !== process.getuid() || (file.mode & 0o077) !== 0)
      throw new Error(`${path} must be this user's own file, private to them (0600)`);
    return readFileSync(fd, "utf8");
  } finally {
    closeSync(fd);
  }
}

/** A ledger's JSON, or a refusal that names where it came from: a teardown removes nothing then. */
function parseLedger(text, where) {
  try {
    const ledger = JSON.parse(text);
    if (ledger === null || typeof ledger !== "object") throw new Error("not an object");
    return ledger;
  } catch (error) {
    throw new CommandError(
      `the ledger in ${where} cannot be read (${error.message}); nothing was removed. Move it aside to tear down the stack's own infrastructure only.`,
    );
  }
}

/** Every window's file of this daemon's ledger, and the windows that were cut short. */
async function readLedgerFiles() {
  const dir = await ledgerDirectory();
  const windows = (await readdir(dir))
    .filter((name) => name.endsWith(".json"))
    .map((name) => parseLedger(readPrivateFile(join(dir, name)), join(dir, name)));
  return { windows, cutShort: windows.filter((window) => !window.closed) };
}

/**
 * The stack's ledger for this daemon: this cache directory's windows and the copy `up` left in the
 * stack's state volume, merged (the copy read with `--pull never`: a teardown fetches nothing).
 */
async function readLedger(volumes) {
  const { windows, cutShort } = await readLedgerFiles();
  const stateVolume = volumes.find(
    (volume) => volume.Name === STATE_VOLUME && volume.Labels?.[STACK_LABEL] === "1",
  );
  if (stateVolume === undefined) return { ...mergeLedgers(windows), cutShort };
  const copy = await dockerOut([
    "run",
    "--rm",
    "--pull",
    "never",
    ...transient("ledger"),
    "--network",
    "none",
    "--volume",
    `${STATE_VOLUME}:/state:ro`,
    "--entrypoint",
    "sh",
    FIXTURE_BASE_IMAGE,
    "-c",
    "if [ -f /state/ledger.json ]; then cat /state/ledger.json; fi",
  ]).catch(() => "");
  const copies = copy ? [parseLedger(copy, `the state volume's ledger.json`)] : [];
  return { ...mergeLedgers([...windows, ...copies]), cutShort };
}

async function report(args) {
  const { flags } = parseFlags(args);
  const state = await readState();
  if (!state) throw new Error("no verify stack here: `up` starts one");
  const memory = await measureMemory(state);
  const isolation = isolationFindings(await inspectAll(await stackContainers()), outerSecrets);
  // Read-only: what it measures is printed with the stack's state, never written back.
  const measured = {
    memory: {
      at: new Date().toISOString(),
      method: memory.method,
      totalKb: memory.totalKb,
      top: memory.processes.slice(0, 12),
    },
    isolation: { checked: outerSecrets.length, findings: isolation },
  };
  if (flags.json) return say(JSON.stringify({ ...state, ...measured }, null, 2));
  say(`verify stack · ${state.phase ?? "ready"}`);
  for (const source of Object.values(state.sources))
    say(`  ${source.description ?? "pinned (the release Mend pins)"}`);
  say(`  web · ${state.url} (from the session: ${relayOrigin(state)})`);
  for (const [phase, seconds] of Object.entries(state.phases))
    say(`  ${phase.padEnd(22)} ${formatSeconds(seconds)}`);
  if (state.check)
    say(
      `  check: ${state.check.command} · ${state.check.status} · ${formatSeconds(state.check.seconds)}`,
    );
  say(`  memory · ${formatKb(memory.totalKb)} · ${memory.method}`);
  for (const item of memory.processes.slice(0, 8))
    say(`    ${formatKb(item.kb).padStart(9)}  ${item.command}`);
  // What was looked at, and only that: each container's environment, command and labels.
  say(
    outerSecrets.length === 0
      ? "  isolation · not checked: no credential of the session is readable here"
      : isolation.length === 0
        ? `  isolation · the session's credential (${outerSecrets.length} value(s)) is in no container's environment, command or labels`
        : `  isolation · FOUND in ${isolation.join(", ")}`,
  );
  if (isolation.length > 0) process.exitCode = 1;
}

// ─── down ───────────────────────────────────────────────────────────────────

async function down(args) {
  const { flags } = parseFlags(args);
  const owner = await currentClaim(dockerOut);
  const volumes = (await dockerOut(["volume", "ls", "--quiet"])).split("\n").filter(Boolean);
  let removed = null;
  if (owner.state === "present") {
    await takeDown(owner.claim ?? "", (counts) => (removed = counts));
  } else if (volumes.includes(STATE_VOLUME) || flags.force) {
    // Remains with no generation (a start killed before it claimed): this process holds the
    // daemon's lock exclusively, so no start is building beside the sweep.
    removed = await removeResources(null);
  } else if (!flags.purge) {
    throw new Error("no verify stack on this daemon (--force sweeps what one left anyway)");
  }
  if (flags.purge) await purgeCaches();
  say(
    `verify stack · removed ${removed?.containers ?? 0} container(s), ${removed?.volumes ?? 0} volume(s)${flags.purge ? "; images, build cache and every cache directory purged" : "; images kept for the next up"}`,
  );
}

/**
 * Take generation `claimId` down (lifecycle.mjs `teardownGeneration`), under the daemon's lock held
 * exclusively: `"removed"`, `"gone"` or `"not-ours"`. `onRemoved` hears the counts.
 */
const takeDown = (claimId, onRemoved = () => {}) =>
  teardownGeneration({
    docker: dockerOut,
    claimId,
    removeResources: async (ownerId) => onRemoved(await removeResources(ownerId)),
  });

/**
 * What the stack's ledger recorded and its own infrastructure (lib.mjs `planTeardown`), then
 * `ownerId` last. It runs only under the daemon's lock held exclusively, so no start of the stack
 * records or builds meanwhile. Nothing else is removed: what looks like the stack's but is not in
 * the ledger is reported with the commands that remove it by hand. When a removal fails, the state
 * volume and the ledger stay, so the next teardown tries again; the state file goes before the
 * owner, so no later generation's state is ever this one's to remove.
 */
async function removeResources(ownerId) {
  const now = await inventory();
  const ledger = await readLedger(now.volumes);
  const plan = planTeardown({ ledger, ...now });
  const failures = [];
  const remove = (args, what) =>
    docker(args).then(
      () => say(`verify stack · removed ${what}`),
      (error) => failures.push(`${what} (${error.message})`),
    );
  for (const item of plan.containers)
    await remove(
      ["rm", "--force", "--volumes", item.Id],
      `container ${item.Name.replace(/^\//, "")} (${item.Id.slice(0, 12)})`,
    );
  for (const volume of plan.volumes.filter((item) => item.Name !== STATE_VOLUME))
    await remove(["volume", "rm", "--force", volume.Name], `volume ${volume.Name}`);
  // A network holds no data: one still in use by something unrecorded is reported, not retried.
  for (const network of plan.networks)
    await docker(["network", "rm", network.Id]).then(
      () => say(`verify stack · removed network ${network.Name}`),
      () =>
        say(
          `verify stack · left network ${network.Name}: something the stack did not make uses it`,
        ),
    );
  for (const window of ledger.cutShort)
    say(
      `verify stack · a recording that began ${window.startedAt} was cut short: what it made in its last seconds is not recorded`,
    );
  const why = {
    "made again": "made again after the stack recorded it",
    "not the stack's shape":
      "made while a recording was open, but shaped like nothing the stack makes",
    "not recorded": "shaped like the stack's, but never recorded as made by it",
  };
  for (const [reason, says] of Object.entries(why)) {
    const items = plan.leftAlone.filter((item) => item.reason === reason);
    if (items.length > 0)
      say(
        `verify stack · left alone (${says}): ${items.map((item) => `${item.kind} ${item.name}`).join(", ")}`,
      );
  }
  if (plan.leftAlone.length > 0) {
    say("  to remove them by hand, if they are the stack's:");
    for (const line of manualRemoval(plan.leftAlone)) say(`    ${line}`);
  }
  if (failures.length > 0)
    throw new CommandError(
      `could not remove ${failures.join("; ")}; the ledger is kept, so the next down tries again`,
    );
  if (plan.volumes.some((item) => item.Name === STATE_VOLUME))
    await remove(["volume", "rm", "--force", STATE_VOLUME], `volume ${STATE_VOLUME}`);
  await rm(await ledgerDirectory(), { recursive: true, force: true });
  // The state file names one daemon's stack: another daemon's teardown leaves it.
  const state = await readState();
  if (state !== null && (state.daemon === undefined || state.daemon === (await daemonKey())))
    await rm(stateFile, { force: true });
  if (ownerId !== null) await docker(["rm", "--force", ownerId]);
  return {
    containers: plan.containers.length + (ownerId === null ? 0 : 1),
    volumes: plan.volumes.length,
  };
}

/**
 * Everything the stack keeps for its next start: its images, BuildKit's cache on this daemon (layers
 * and cache mounts, cargo's included), and its cache directories (contexts, packed packages, the
 * bare repositories, logs). Works with or without a stack up.
 */
async function purgeCaches() {
  const images = (await dockerOut(["image", "ls", "--quiet", "--filter", `label=${STACK_LABEL}=1`]))
    .split("\n")
    .filter(Boolean);
  if (images.length > 0)
    await docker(["image", "rm", "--force", ...new Set(images)]).catch(() => undefined);
  await ensureBuildx();
  await docker(["buildx", "prune", "--all", "--force"]);
  for (const dir of ["contexts", "packages", "git", "logs"])
    await rm(join(cacheDir, dir), { recursive: true, force: true });
}

/** How many entries each cache directory keeps across starts; older ones go at the next `up`. */
const RETENTION = { contexts: 6, packages: 6, logs: 10 };

async function trimCaches() {
  for (const [dir, keep] of Object.entries(RETENTION)) {
    const root = join(cacheDir, dir);
    const entries = [];
    for (const name of await readdir(root).catch(() => [])) {
      // An entry that vanished or cannot be read is skipped, not fatal: trimming is housekeeping.
      const info = await lstat(join(root, name)).catch(() => null);
      if (info !== null) entries.push({ name, mtimeMs: info.mtimeMs });
    }
    for (const name of beyondRetention(entries, keep))
      await rm(join(root, name), { recursive: true, force: true }).catch((error) =>
        say(`verify stack · could not trim ${dir}/${name}: ${error.message}`),
      );
  }
}

// ─── serve ──────────────────────────────────────────────────────────────────

/**
 * `up`, then hold while the Service runs. The Service's port is the relay's: Mend dials the
 * workspace loopback, then the Docker sidecar.
 *
 * The stack goes when this process goes, however it goes. Mend stops a Service by hanging up its
 * terminal (SIGHUP to the process group, SIGKILL two seconds later, sealantd `sealant-pty` close),
 * a verifier may be killed outright, and `up` may fail. So the teardown does not run here but in a
 * watchdog, a process in a session of its own, out of the group's reach (lifecycle.mjs `watch`).
 * The watchdog also makes the claim, when this process asks: a create still in flight when this
 * process dies belongs to the watchdog, which waits for it however long it takes and then takes
 * down what it created. It takes down only its own generation. A start that ends holding no claim
 * stops its watchdog.
 */
async function serve(args) {
  const claimId = randomUUID();
  const watcher = startWatchdog(claimId);
  for (const signal of ["SIGHUP", "SIGTERM", "SIGINT"]) process.on(signal, () => process.exit(0));
  // The watchdog says when it listens, then answers the one claim request with the outcome.
  const replies = [];
  const waiting = [];
  // A channel that breaks is a watchdog that went away: `exited` says so; it never kills this one.
  watcher.on("error", () => undefined);
  watcher.on("message", (message) => {
    const waiter = waiting.shift();
    if (waiter) waiter(message);
    else replies.push(message);
  });
  const exited = new Promise((_, fail) =>
    watcher.once("exit", () => fail(new Error("the watchdog exited before it claimed"))),
  );
  exited.catch(() => undefined);
  const reply = () =>
    Promise.race([
      new Promise((done) => (replies.length > 0 ? done(replies.shift()) : waiting.push(done))),
      exited,
    ]);
  const claimWith = async () => {
    await reply(); // { ready: true }
    await new Promise((sent, fail) => {
      watcher.send({ claim: true }, (error) => {
        if (error) fail(error);
        else sent();
      });
    });
    const answer = await reply();
    // The channel has done its work: it no longer holds this process open.
    watcher.channel?.unref();
    if (answer?.claimed === true) return;
    throw new Error(answer?.claimed === false ? CLAIM_REFUSED : answer?.error);
  };
  let state;
  try {
    state = await up(args, { claimId, claimWith });
  } catch (error) {
    const owner = await currentClaim(dockerOut).catch(() => null);
    if (owner !== null && !(owner.state === "present" && owner.claim === claimId)) {
      try {
        process.kill(watcher.pid, "SIGTERM");
      } catch {
        // Already gone.
      }
    }
    throw error;
  }
  say(
    `verify stack · on your machine: mend service connect stack --port ${state.relay.port}, then open ${state.url}`,
  );
  say(
    "verify stack · sign in: node scripts/verify-stack/stack.mjs mend invite --role owner --days 1",
  );
  let last = null;
  for (;;) {
    const healthy = await fetch(`${relayOrigin(state)}/api/health`, {
      signal: AbortSignal.timeout(5000),
    }).then(
      (response) => response.ok,
      () => false,
    );
    if (healthy !== last) say(`verify stack · health ${healthy ? "answers" : "does not answer"}`);
    last = healthy;
    await pause(30_000);
  }
}

/**
 * A running process's start time (field 22 of /proc/<pid>/stat), so a reused pid is not mistaken
 * for it; null once it has ended, a zombie (state Z) included: nothing may have reaped it yet.
 */
const startTimeOf = (pid) => {
  try {
    const line = readFileSync(`/proc/${pid}/stat`, "utf8");
    const fields = line.slice(line.lastIndexOf(")") + 2).split(" ");
    if (fields[0] === "Z" || fields[0] === "X") return null;
    return fields[19] ?? null;
  } catch {
    return null;
  }
};

function startWatchdog(claimId) {
  const log = join(cacheDir, "logs", "watchdog.log");
  mkdirSync(dirname(log), { recursive: true });
  const out = openSync(log, "a");
  const started = startTimeOf(process.pid) ?? "";
  const child = spawn(
    process.execPath,
    [fileURLToPath(import.meta.url), "watchdog", String(process.pid), started, claimId],
    { detached: true, stdio: ["ignore", out, out, "ipc"], env: process.env },
  );
  child.unref();
  say(`verify stack · watchdog holds the stack to this process (log: ${log})`);
  return child;
}

/**
 * `watchdog <pid> <start time> <claim id>`: makes the claim when its supervisor asks (over IPC),
 * waits for the supervisor to end, then takes the generation down (lifecycle.mjs `watch`) through
 * `teardown`, a command that holds the daemon's lock exclusively.
 */
async function watchdog([pid, started, claimId]) {
  if (!claimId) throw new Error("watchdog needs the claim id it guards");
  const log = (line) => say(`${new Date().toISOString()} verify stack · ${pid} · ${line}`);
  // Nothing on the IPC channel ends this process: an error there is a supervisor gone.
  process.on("error", (error) => log(`ipc: ${error.code ?? error.message}`));
  let attempt = null;
  // Once the watchdog has settled whether this start holds a claim, it makes none: a request still
  // in the pipe from a supervisor that has died must not start a create nobody would watch.
  let settled = false;
  process.on("message", (message) => {
    if (message?.claim !== true || attempt !== null || settled) return;
    attempt = claim(dockerOut, { claimId, image: FIXTURE_BASE_IMAGE });
    void (async () => {
      try {
        const claimed = await attempt;
        log(claimed ? "claimed the daemon" : "refused: another start holds the daemon");
        sendSafely(process, { claimed }, log);
      } catch (error) {
        sendSafely(process, { error: error.message }, log);
      }
    })();
  });
  sendSafely(process, { ready: true }, log);
  // The channel never keeps this process alive; the supervisor's life does.
  process.channel?.unref();
  const outcome = await watch({
    alive: () => {
      const now = startTimeOf(pid);
      return now !== null && (started === "" || now === started);
    },
    claimed: () => {
      settled = true;
      return settleClaim({ attempt, docker: dockerOut, claimId, pause, log });
    },
    remove: () => runTeardown(claimId),
    pause,
    log,
  });
  log(
    {
      "taken-down": "the stack is down",
      gone: "no generation is up; nothing to take down",
      "not-ours": "the daemon's claim is another start's; nothing touched",
      "never-claimed": "this start never held a claim; nothing touched",
    }[outcome],
  );
}

/** What `teardown` exits with for each outcome; anything else is a failure to retry. */
const TEARDOWN_EXIT = { removed: 0, gone: 3, "not-ours": 4 };

/**
 * Run `teardown <claim id>` (which waits for the daemon's lock, exclusively) and answer its
 * outcome. Its output goes to this process's own (the watchdog's log).
 */
function runTeardown(claimId) {
  return new Promise((done, fail) => {
    const child = spawn(process.execPath, [fileURLToPath(import.meta.url), "teardown", claimId], {
      stdio: ["ignore", "inherit", "inherit"],
      env: process.env,
    });
    child.once("error", fail);
    child.once("close", (code) => {
      const outcome = Object.entries(TEARDOWN_EXIT).find(([, exit]) => exit === code)?.[0];
      if (outcome) done(outcome);
      else fail(new Error(`teardown exited ${code}`));
    });
  });
}

/** `teardown <claim id>`: take that generation down, holding the daemon's lock exclusively. */
async function teardown([claimId]) {
  const outcome = await takeDown(claimId ?? "", (removed) =>
    say(`verify stack · removed ${removed.containers} container(s), ${removed.volumes} volume(s)`),
  );
  process.exitCode = TEARDOWN_EXIT[outcome];
}

// ─── the daemon's lock ──────────────────────────────────────────────────────

/** This Docker daemon, as the lock and the ledger name it: a digest of `docker info`'s id. */
let daemonKeyOnce = null;
const daemonKey = () =>
  (daemonKeyOnce ??= dockerOut(["info", "--format", "{{.ID}}"]).then((id) =>
    digestOf(id).slice(0, 16),
  ));

/**
 * `dir`, made if it is missing, and checked: a directory of this user's, private to them (0700), and
 * no symlink. The lock and the ledger live in such directories, so nobody else can plant or hold
 * them. Returns `dir`.
 */
function privateDirectory(dir) {
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  const where = lstatSync(dir);
  if (!where.isDirectory() || where.uid !== process.getuid() || (where.mode & 0o077) !== 0)
    throw new Error(
      `${dir} must be a directory of this user's, private to them (0700) and no symlink: the stack's lock and ledger live there`,
    );
  return dir;
}

/**
 * The lock file of this Docker daemon (`docker info` names it), private to the person: in a
 * directory of theirs, 0700, that is no symlink, opened 0600 without following one, and checked once
 * open to be their own regular file, so nobody else can create it first or hold it. Two people who
 * share one daemon therefore hold different locks: the daemon's claim still lets one stack up at a
 * time, but neither's teardown waits for the other's start (docs/operations/verify-stack.md).
 * Returns the open descriptor.
 */
async function openDaemonLock() {
  const dir = privateDirectory(join(cacheDir, "locks"));
  const path = join(dir, `${await daemonKey()}.lock`);
  const fd = openSync(path, constants.O_RDONLY | constants.O_CREAT | constants.O_NOFOLLOW, 0o600);
  const file = fstatSync(fd);
  if (!file.isFile() || file.uid !== process.getuid() || (file.mode & 0o077) !== 0) {
    closeSync(fd);
    throw new Error(`${path} must be this user's own file, private to them (0600)`);
  }
  return fd;
}

const BUSY =
  "this daemon's stack is busy: a serve, up, mend or check holds it (it may be building), or a teardown is under way. Stop serve to cancel it (mend service stop stack); its watchdog takes the stack down.";

/**
 * Take the daemon's lock, flock(2) through util-linux `flock` on a descriptor this process keeps
 * open: `shared` for a start (waits up to 10 minutes for a teardown to end), `exclusive` for `down`
 * (refused at once while a start or a teardown holds it), `exclusive-wait` for a watchdog's
 * teardown (waits for the start and every command it left running). The lock belongs to this
 * process's open file, which the kernel closes when the last process holding it ends, however it
 * ends, and so releases the lock.
 */
async function lockDaemon(mode) {
  const flock = await exec("flock", ["--version"], { env: process.env }).then(
    () => true,
    () => false,
  );
  if (!flock)
    throw new Error(
      "the verify stack needs flock(1) (util-linux) to hold its daemon's lock; it runs on Linux, as Mend sessions do",
    );
  lockFd = await openDaemonLock();
  const how = {
    shared: ["-s", "-w", "600"],
    exclusive: ["-x", "-n"],
    "exclusive-wait": ["-x"],
  }[mode];
  await exec("flock", [...how, String(LOCK_FD)], {
    env: process.env,
    timeout: 24 * 3600_000,
  }).catch(() => {
    closeSync(lockFd);
    lockFd = null;
    throw new Error(
      mode === "shared" ? "a teardown of this daemon's stack did not end within 10 minutes" : BUSY,
    );
  });
}

// ─── main ───────────────────────────────────────────────────────────────────

const HELP = `usage: node scripts/verify-stack/stack.mjs <command>

  up [sources] [--port <n>] [--no-check] [--keep]
                                           build and start the stack, then run the check
                                           (--keep: leave a failed start for a look)
  serve [sources] [--port <n>]             up, then hold; the stack goes when this stops
  mend <args…>                             the inner mend CLI, signed in as the first account
  check                                    inner mend run -- true, until its session settles
  report [--json]                          sources, timings, memory, isolation
  down [--purge] [--force]                 remove the stack (--purge: images, build cache, caches)

sources: --mend|--sealant|--sealantd <path|#pr|ref|pinned> (pinned: Core and sealantd only)
docs/operations/verify-stack.md has the rest.`;

async function main() {
  const [command, ...args] = process.argv.slice(2);
  switch (command) {
    case "up":
      await lockDaemon("shared");
      await up(args);
      return;
    case "serve":
      await lockDaemon("shared");
      await serve(args);
      return;
    case "teardown":
      await lockDaemon("exclusive-wait");
      await teardown(args);
      return;
    case "mend": {
      await lockDaemon("shared");
      const state = await readState();
      if (!state) throw new Error("no verify stack here: `up` starts one");
      // The inner CLI's own exit is this command's: its output went straight to the terminal. What
      // it makes on the daemon (an inner session's containers) goes into the ledger.
      await recording(() =>
        cliRun(state, args, { stdio: "inherit", timeout: 24 * 3600_000 }).catch((error) => {
          if (!(error instanceof CommandError)) throw error;
          process.exitCode = 1;
        }),
      );
      return;
    }
    case "watchdog":
      await watchdog(args);
      return;
    case "check": {
      await lockDaemon("shared");
      const state = await readState();
      if (!state) throw new Error("no verify stack here: `up` starts one");
      await recording(() => check(state));
      await writeState(state);
      return;
    }
    case "report":
      await report(args);
      return;
    case "down":
      await lockDaemon("exclusive");
      await down(args);
      return;
    case undefined:
    case "help":
    case "--help":
      say(HELP);
      return;
    default:
      throw new Error(`unknown command ${command}\n${HELP}`);
  }
}

main().catch((error) => {
  process.stderr.write(`verify stack: ${error.message}\n`);
  process.exit(1);
});
