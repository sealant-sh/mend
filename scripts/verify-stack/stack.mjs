// A full Mend stack built from source inside one Docker daemon, normally a Mend session's own:
// sealantd, Sealant Core (API, worker, SSH gateway) and Mend, each at a ref, installed with the
// product's own `mend server setup`, so a verifier can drive a change that spans the three
// repositories. docs/operations/verify-stack.md says how to use it; mend.toml declares it as the
// `stack` Service.
//
//   node scripts/verify-stack/stack.mjs up [sources] [--port <n>] [--no-check]
//   node scripts/verify-stack/stack.mjs serve [sources] [--port <n>]   up, then hold; down on exit
//   node scripts/verify-stack/stack.mjs mend <args…>                     the inner CLI
//   node scripts/verify-stack/stack.mjs check                           inner mend run -- true
//   node scripts/verify-stack/stack.mjs report [--json]                 sources, timings, memory
//   node scripts/verify-stack/stack.mjs down [--purge]                  remove the stack
//
// Sources: --mend, --sealant, --sealantd, each a path (a working tree as it is), #<pr>, a branch,
// tag or commit on GitHub, or `pinned` (Core and sealantd: the release Mend pins, no build).
// Defaults: this checkout for Mend; /workspace/repos/<name> when `mend repo add` brought it into
// the session, else main.
//
// What it never does: put a secret in argv, a log or a capture root. The inner server's secrets
// are generated by `mend server setup` inside a container and live in a Docker volume of this
// daemon; its first account's password and token are written there too. Docker clients run with
// an environment of their own (lib.mjs dockerClientEnvironment): no MEND_* variable of the session
// reaches them, so nothing of the stack holds a credential of the outer server.

