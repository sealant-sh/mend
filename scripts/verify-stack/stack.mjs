/**
 * Build one image unless this daemon already holds it under its tag (the same tree was built
 * before). `dockerfile` is a path in the context, or `{ text }` for a Dockerfile the stack owns.
 */
async function build(logs, name, { context, dockerfile, tag, args = {}, labels = {} }) {
  if (await imageId(tag)) return "reused";
  const log = join(logs, `${name}.log`);
  const argv = ["build", "--tag", tag, "--label", `${STACK_LABEL}=1`];
  for (const [key, value] of Object.entries(labels)) argv.push("--label", `${key}=${value}`);
  for (const [key, value] of Object.entries(args)) argv.push("--build-arg", `${key}=${value}`);
  const text = typeof dockerfile === "string" ? undefined : dockerfile.text;
  argv.push("--file", text === undefined ? join(context, dockerfile) : "-", context);
  await docker(argv, { log, input: text });
  return "built";
}

