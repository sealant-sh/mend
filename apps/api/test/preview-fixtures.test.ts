import { createHash } from "node:crypto";
import { once } from "node:events";
import * as http from "node:http";
import * as net from "node:net";

import { afterEach, describe, expect, it } from "vitest";
import { WebSocket } from "ws";

import {
  type DigestAnswer,
  type EchoedHeaders,
  type FixtureKind,
  type RunningFixture,
  serveFixture,
  type SseEvent,
  spawnFixture,
} from "./fixtures/preview/apps.ts";
import { uploadGenerated } from "./support/preview-bytes.ts";

const running: RunningFixture[] = [];
afterEach(async () => {
  for (const fixture of running.splice(0)) await fixture.stop();
});

const serve = async (kind: FixtureKind) => {
  const fixture = await serveFixture(kind);
  running.push(fixture);
  return fixture;
};

/** Byte `i` is `i % 251`, built whole: the independent expectation for small payloads. */
const expectedBytes = (n: number) => Buffer.from(Array.from({ length: n }, (_, i) => i % 251));
const sha256 = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");

const get = (port: number, path: string, headers: http.OutgoingHttpHeaders = {}) =>
  new Promise<{ status: number; headers: http.IncomingHttpHeaders; body: Buffer }>(
    (resolve, reject) => {
      const request = http.get({ host: "127.0.0.1", port, path, headers }, (response) => {
        const parts: Buffer[] = [];
        response.on("data", (chunk: Buffer) => parts.push(chunk));
        response.on("end", () =>
          resolve({
            status: response.statusCode ?? 0,
            headers: response.headers,
            body: Buffer.concat(parts),
          }),
        );
      });
      request.on("error", reject);
    },
  );

const parsed = <A>(body: Buffer): A => JSON.parse(body.toString("utf8"));

describe("digest sink and upload client", () => {
  const N = 1_048_576 + 12_345;

  it.each([
    { name: "content-length", chunked: false, expectContinue: false },
    { name: "chunked", chunked: true, expectContinue: false },
    { name: "expect 100-continue", chunked: false, expectContinue: true },
  ])("hashes a $name body as it arrives", async ({ chunked, expectContinue }) => {
    const sink = await serve("digest");
    const result = await uploadGenerated(`http://127.0.0.1:${sink.port}/upload/a?b=1&b=2`, {
      bytes: N,
      method: "PUT",
      chunked,
      expectContinue,
    });
    const answer = parsed<DigestAnswer>(Buffer.from(result.body));
    const expected = sha256(expectedBytes(N));
    expect(result.status, "the sink answers 200").toBe(200);
    expect(result.sentBytes, "the client sent every byte").toBe(N);
    expect(result.sentSha256, "the client hashed what it sent").toBe(expected);
    expect(answer, "the sink saw the method, exact target and whole body").toMatchObject({
      method: "PUT",
      path: "/upload/a?b=1&b=2",
      bytes: N,
      sha256: expected,
    });
    expect(answer.headers["transfer-encoding"], "framing as sent").toBe(
      chunked ? "chunked" : undefined,
    );
    expect(result.continued, "Continue only when asked for").toBe(expectContinue);
  });

  it("reads at the bounded rate it is given", async () => {
    const sink = await serve("digest");
    const started = performance.now();
    const result = await uploadGenerated(`http://127.0.0.1:${sink.port}/?rate=1048576`, {
      bytes: 512 * 1024,
    });
    const elapsed = performance.now() - started;
    expect(parsed<DigestAnswer>(Buffer.from(result.body)).bytes, "whole body").toBe(512 * 1024);
    expect(elapsed, "512 KiB at 1 MiB/s takes about half a second").toBeGreaterThan(350);
  });
});

describe("download", () => {
  it("streams n generated bytes with Content-Length", async () => {
    const app = await serve("download");
    const response = await get(app.port, "/bytes?n=200003");
    expect(response.headers["content-length"], "declared length").toBe("200003");
    expect(sha256(response.body), "the pattern, whole").toBe(sha256(expectedBytes(200_003)));
  });

  it("streams chunked without Content-Length when asked", async () => {
    const app = await serve("download");
    const response = await get(app.port, "/bytes?n=70000&chunked=1");
    expect(response.headers["transfer-encoding"], "chunked framing").toBe("chunked");
    expect(response.headers["content-length"], "no declared length").toBeUndefined();
    expect(response.body.length, "whole body").toBe(70_000);
  });
});

describe("server-sent events", () => {
  it("flushes each event when sent, spaced as asked", async () => {
    const app = await serve("sse");
    const arrivals: Array<{ event: SseEvent; at: number }> = [];
    await new Promise<void>((resolve, reject) => {
      http
        .get(
          { host: "127.0.0.1", port: app.port, path: "/events?every=400&count=3" },
          (response) => {
            expect(response.headers["content-type"], "an event stream").toBe("text/event-stream");
            let pending = "";
            response.setEncoding("utf8");
            response.on("data", (text: string) => {
              pending += text;
              const frames = pending.split("\n\n");
              pending = frames.pop() ?? "";
              for (const frame of frames) {
                const data = frame.split("\n").find((line) => line.startsWith("data: "));
                if (data !== undefined)
                  arrivals.push({ event: JSON.parse(data.slice(6)), at: Date.now() });
              }
            });
            response.on("end", () => resolve());
          },
        )
        .on("error", reject);
    });
    expect(
      arrivals.map((arrival) => arrival.event.i),
      "every event, in order",
    ).toEqual([0, 1, 2]);
    const gaps = arrivals.slice(1).map((arrival, index) => arrival.at - (arrivals[index]?.at ?? 0));
    for (const gap of gaps) expect(gap, "events arrive spaced, not batched").toBeGreaterThan(300);
  });
});

describe("websocket echo", () => {
  it("echoes text and binary messages", async () => {
    const app = await serve("websocket");
    const client = new WebSocket(`ws://127.0.0.1:${app.port}/socket`);
    await once(client, "open");
    const replies: Array<{ data: Buffer; binary: boolean }> = [];
    client.on("message", (data: Buffer, binary: boolean) => replies.push({ data, binary }));
    client.send("hello");
    client.send(Buffer.from([0, 1, 2, 255]));
    while (replies.length < 2) await new Promise((resolve) => setTimeout(resolve, 10));
    client.close();
    expect(replies.map((reply) => [reply.data.toString("hex"), reply.binary])).toEqual([
      [Buffer.from("hello").toString("hex"), false],
      ["000102ff", true],
    ]);
  });

  it("answers an upgrade to /upgrade-refused with a plain 400", async () => {
    const app = await serve("websocket");
    const client = new WebSocket(`ws://127.0.0.1:${app.port}/upgrade-refused`);
    const [request, response] = await once(client, "unexpected-response");
    if (request instanceof http.ClientRequest) request.destroy();
    expect(response instanceof http.IncomingMessage && response.statusCode, "400, no 101").toBe(
      400,
    );
  });
});

describe("cookies", () => {
  it("sets the cookies the gateway must handle, and Clear-Site-Data", async () => {
    const app = await serve("cookies");
    const response = await get(app.port, "/set-cookies");
    const cookies = response.headers["set-cookie"] ?? [];
    expect(cookies.length, "several Set-Cookie values, not one folded").toBeGreaterThanOrEqual(5);
    expect(
      cookies.some((cookie) => /;\s*Domain=/i.test(cookie)),
      "one with Domain=",
    ).toBe(true);
    expect(
      cookies.some((cookie) => /;\s*Expires=[^;]*,/i.test(cookie)),
      "one whose Expires holds a comma",
    ).toBe(true);
    expect(
      cookies.some((cookie) => /;\s*HttpOnly/i.test(cookie)),
      "one HttpOnly",
    ).toBe(true);
    expect(
      cookies.some((cookie) => cookie.startsWith("__Host-mend-preview=")),
      "one named like the grant",
    ).toBe(true);
    expect(response.headers["clear-site-data"], "Clear-Site-Data").toContain("cookies");
  });

  it("echoes the request headers it saw", async () => {
    const app = await serve("cookies");
    const response = await get(app.port, "/echo-headers", {
      cookie: "a=1; b=2",
      "x-probe": "seen",
    });
    const echoed = parsed<EchoedHeaders>(response.body);
    expect(echoed.headers.cookie, "the cookie header").toBe("a=1; b=2");
    expect(echoed.rawHeaders, "raw pairs as sent").toContainEqual(["x-probe", "seen"]);
  });
});

describe("all routes on one port, in a child process", () => {
  it("serves every fixture and stops", async () => {
    const app = await spawnFixture("all");
    const download = await get(app.port, "/bytes?n=1000");
    const upload = await uploadGenerated(`http://127.0.0.1:${app.port}/anything`, { bytes: 1000 });
    const echoed = await get(app.port, "/echo-headers");
    await app.stop();
    expect(download.body.length, "download route").toBe(1000);
    expect(parsed<DigestAnswer>(Buffer.from(upload.body)).sha256, "digest for other paths").toBe(
      sha256(expectedBytes(1000)),
    );
    expect(echoed.status, "cookies route").toBe(200);
    const refused = await new Promise<string>((resolve) => {
      const socket = net.connect({ host: "127.0.0.1", port: app.port });
      socket.once("connect", () => {
        socket.destroy();
        resolve("connected");
      });
      socket.once("error", (error: NodeJS.ErrnoException) => resolve(error.code ?? "error"));
    });
    expect(refused, "nothing listens after stop").toBe("ECONNREFUSED");
  });
});
